/* ==========================================================================
 * [FILE 객체 심화 탐구: 스트림, 버퍼, 그리고 내부 메커니즘]
 *
 * 1. 스트림(Stream)이란 무엇인가?
 *    - 컴퓨터 과학에서 스트림은 '데이터가 수도꼭지에서 물 흐르듯 연속해서 흘러가는 통로'를 의미함.
 *    - C언어에서 파일 입출력, 키보드 입력(stdin), 모니터 출력(stdout) 모두 이 스트림 개념으로 다뤄짐.
 *      즉, 데이터가 파일에서 프로그램으로 들어오면 입력 스트림, 프로그램에서 파일로 나가면 출력 스트림임.
 *
 * 2. 버퍼(Buffer)의 역할과 동작 원리
 *    - 하드디스크나 SSD는 바이트 단위로 직접 읽고 쓸 때 물리적인 디스크 헤드 이동이나 플래시 메모리
 *      블록 연산 때문에 속도가 매우 느림.
 *    - 이를 해결하기 위해 C언어 라이브러리는 메모리(RAM) 위에 일정 크기의 임시 공간(버퍼, 보통 4KB~8KB)을 둠.
 *    - 쓰기(`fprintf` 등): 프로그램이 데이터를 보내면 곧바로 디스크에 쓰지 않고 버퍼에 차곡차곡 쌓음.
 *      버퍼가 꽉 차거나, `fflush()`를 호출하거나, `fclose()`로 파일을 닫을 때 비로소 디스크로 한꺼번에 왕창 기록됨.
 *    - 읽기(`fscanf` 등): 디스크에서 데이터를 읽을 때 한 바이트씩 가져오는 게 아니라, 왕창 읽어서
 *      버퍼에 담아둔 뒤 프로그램이 요청할 때마다 버퍼에서 빠르게 꺼내줌.
 *
 * 3. FILE 객체(구조체)의 내부 구성 요소와 저장/추출 형태
 *    - `FILE`은 컴파일러가 제공하는 불투명 구조체(Opaque Structure)로, 내부 필드는 시스템마다 다를 수 있지만
 *      대략 다음과 같은 핵심 정보를 담고 있음:
 *      * 파일 디스크립터(File Descriptor): 운영체제(OS)가 파일을 관리하기 위해 부여하는 정수 번호.
 *      * 버퍼 포인터와 상태 변수: 현재 버퍼의 시작 주소, 끝 주소, 그리고 지금 어디까지 채워졌는지를 가리키는 포인터.
 *      * 파일 오프셋(Position Indicator): 파일 내부에서 현재 읽거나 쓸 위치(커서)를 가리키는 바이트 오프셋.
 *        (`ftell()`로 확인하고 `fseek()`로 이 위치를 자유롭게 옮길 수 있음)
 *      * 모드 및 에러 플래그: 읽기 전용인지 쓰기 전용인지, 파일 끝(EOF)에 도달했는지, 에러가 났는지 기록하는 상태 변수.
 *
 * 4. 무엇이 저장되고 무엇이 꺼내지는가?
 *    - 텍스트 모드("w", "r"): 프로그램의 문자열이 운영체제의 개행 문자 규칙(예: Windows의 \r\n과 Linux의 \n)에
 *      맞게 변환되며 스트림을 타고 디스크와 프로그램 사이를 오감.
 *    - 바이너리 모드("wb", "rb"): 변환 없이 메모리에 있는 비트/바이트 그대로(구조체나 이미지 데이터 등)
 *      버퍼를 거쳐 파일로 고스란히 저장되거나 꺼내짐.
 * ========================================================================== 
 */

#include <stdio.h>
#include <stdlib.h>

int main(void) {
    // 1. 스트림 열기: "data.txt"에 쓰기(Write) 스트림을 생성함.
    // 이 순간 OS는 파일 디스크립터를 할당하고, 메모리에 FILE 구조체와 출력 버퍼를 준비함.
    FILE* fp = fopen("data.txt", "w");

    if (fp == NULL) {
        printf("파일 열기 실패\n");
        return 1;
    }

    // 2. 버퍼로의 데이터 적재 (아직 디스크가 아니라 RAM의 버퍼에 쌓임)
    fprintf(fp, "첫 번째 줄: 버퍼링 테스트 데이터\n");
    fprintf(fp, "두 번째 줄: 아직 디스크에 안 갔을 수도 있음\n");

    // 파일 오프셋(커서) 위치 확인: 현재 파일 내에서 몇 번째 바이트를 가리키고 있는지 확인
    long current_pos = ftell(fp);
    printf("현재 파일 오프셋(위치): %ld 바이트\n", current_pos);

    // 3. 스트림 닫기 및 버퍼 플러시(Flush)
    // fclose가 호출되는 순간, 메모리 버퍼에 남아있던 잔여 데이터가 하드디스크에 완전히 기록되고 
    // FILE 구조체와 스트림, 파일 디스크립터가 안전하게 소멸됨.
    fclose(fp);

    printf("파일 쓰기 및 스트림 해제 완료\n");
    return 0;
}