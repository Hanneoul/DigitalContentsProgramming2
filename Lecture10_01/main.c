/*
==============================================================================
 [강의 자료] Lecture10_01 | 전투 일지 | 용사는 퇴근해도 기록은 남는다
==============================================================================

1. 오늘의 게임 장면
    공격하고 골드를 주웠다. 창을 닫으면 화면의 글자는 사라진다.
    다음 접속에도 읽으려면 화면이 아니라 파일에 기록해야 한다.

       공격 / 보상 ---> append_event ---> [battle_log.txt]
                                             |
       전투 일지 <----- show_log <-----------+
    Log(로그)는 항해 일지처럼 사건을 순서대로 남긴 기록이다.

 2. 오늘 필요한 도구
    fopen의 "a"는 append(덧붙이다), "w"는 write(새로 쓰다), "r"은 read이다.
    로그에 "w"를 쓰면 용사의 기억력이 한 줄로 줄어든다.
    FILE *fp는 열린 파일을 다루는 포인터이다. NULL이면 열기 실패이다.
    fprintf(fp, ...)는 목적지가 파일인 printf이다.
    fgets(line, sizeof line, fp)는 배열 크기를 지키며 한 줄을 읽는다.
    읽기에 성공한 줄만 출력한다. while (!feof(fp))는 사용하지 않는다.
    쓰기 결과와 fclose의 닫기 결과를 모두 확인한다.

 3. 작은 실험과 답
    1 → 2 → 0, 재실행 후 3. 공격과 보상 두 줄이 남으면 성공이다.
    공격 문장의 10을 25로 바꾸면 이전 기록도 바뀔까?
    답: 새 기록만 25이다. 파일은 소스 코드와 별개의 저장 공간이다.

 4. 코드 지도
    main → read_choice(제공된 입력 검사) → append_event / show_log.
    직접 작성할 핵심은 append_event의 열기·쓰기·닫기이다.

 [공통 메모]
 파일은 실행 작업 폴더(VS에서는 프로젝트 폴더)에 생성된다.
 바이너리 구조체 저장은 동일 빌드 환경용이며 필드 변경 시 재생성한다.
 제공된 입력 검사보다 파일 처리 함수부터 읽는다. 실패 안내도 실행 결과이다.

==============================================================================
 [실습 코드] 먼저 실행 → 예측 → 추가 부분 작성 → 다시 실행
==============================================================================
*/

/* 파일 및 표준 입출력 함수를 선언한다. */
#include <stdio.h>
#include "../LectureSupport/console.h" // 공통 화면 도구이다.

/* 표준 종료 코드 EXIT_SUCCESS, EXIT_FAILURE를 사용한다. */
#include <stdlib.h>

/* 문자열 길이 및 문자 검색 함수를 사용한다. */
#include <string.h>

/* -------------------------------------------------------------------------
 * 역할: 키보드 한 줄을 검사하여 메뉴 번호로 바꾼다.
 * 입력: prompt = 안내 문자열, maximum = 허용할 가장 큰 메뉴 번호.
 * 반환: 0~maximum은 선택 번호, -1은 입력 종료 또는 입출력 오류.
 * 예: read_choice("Choose: ", 3)은 0, 1, 2, 3 중 하나를 받는다.
 * 잘못된 입력에는 안내 후 다시 입력받고, 너무 긴 줄의 나머지는 소비한다.
 * ------------------------------------------------------------------------- */
static int read_choice(const char *prompt, int maximum)
{
    /* 한 줄을 받을 배열이다. */
    char line[32];

    /* break 또는 return을 만날 때까지 반복한다. */
    for (;;)
    {
        /* 안내를 표시한다. */
        fputs(prompt, stdout);

        /* 출력 버퍼의 안내 문구를 전달한다. 실패하면 입력 처리를 끝낸다. */
        if (fflush(stdout) == EOF)
        {
            /* 메뉴 입력을 계속할 수 없으므로 종료/오류를 나타내는 -1을 반환한다. */
            return -1;
        }

        /* 한 줄 읽기가 실패했거나 입력이 끝나면 더 이상 배열을 해석하지 않는다. */
        if (fgets(line, sizeof line, stdin) == NULL)
        {
            /* 메뉴 입력을 계속할 수 없으므로 종료/오류를 나타내는 -1을 반환한다. */
            return -1;
        }

        /* 줄바꿈 없이 배열이 채워졌고 EOF도 아니라면 너무 긴 입력으로 처리한다. */
        if (strchr(line, '\n') == NULL && feof(stdin) == 0)
        {
            /* 긴 줄에서 아직 읽지 않은 문자 하나를 받는다. EOF도 담도록 int를 쓴다. */
            int ch = getchar();

            /* 줄바꿈과 EOF가 나올 때까지 긴 입력의 나머지를 소비한다. */
            while (ch != '\n' && ch != EOF)
            {
                /* 다음 문자를 읽는다. 줄바꿈 또는 입력 끝이 나오면 반복을 멈춘다. */
                ch = getchar();
            }

            /* 입력 제한을 안내한다. */
            puts("Input too long. Enter one digit.");

            /* 현재 입력의 처리를 끝내고 반복문의 처음으로 돌아가 다시 입력받는다. */
            continue;
        }

        /* 첫 문자가 허용 범위의 숫자가 아니면 다시 입력받는다. */
        if (line[0] < '0' || line[0] > '0' + maximum)
        {
            /* 잘못된 입력을 안내한다. */
            puts("Enter one valid menu digit.");

            /* 현재 입력의 처리를 끝내고 반복문의 처음으로 돌아가 다시 입력받는다. */
            continue;
        }

        /* 첫 숫자 뒤에서 공백·탭·줄바꿈만 몇 칸 이어지는지 센다. */
        size_t space_count = strspn(line + 1, " \t\r\n");

        /* 숫자 한 칸과 공백 구간을 건너뛴 다음 칸의 번호를 구한다. */
        size_t next_index = 1 + space_count;

        /* 다음 칸이 문자열 끝이 아니면 숫자 뒤에 다른 글자가 섞인 입력이다. */
        if (line[next_index] != '\0')
        {
            /* 잘못된 입력을 안내한다. */
            puts("Enter one valid menu digit.");

            /* 현재 입력의 처리를 끝내고 반복문의 처음으로 돌아가 다시 입력받는다. */
            continue;
        }

        /* 문자 '2'에서 문자 '0'을 빼면 정수 2가 된다. */
        int choice = line[0] - '0';

        /* 검사를 통과한 정수 메뉴 번호를 main에 돌려준다. */
        return choice;
    }
}

/* -------------------------------------------------------------------------
 * 역할: 사건 한 줄을 battle_log.txt의 끝에 덧붙인다.
 * 입력: event = 기록할 문자열의 시작 주소. 내용은 수정하지 않는다.
 * 반환: 쓰기와 닫기까지 성공하면 1, 어느 단계라도 실패하면 0.
 * 순서: "a"로 열기 → 한 줄 쓰기 → 닫기 → 성공 여부 반환.
 * ------------------------------------------------------------------------- */
static int append_event(const char *event)
{
    /* 기존 기록 뒤에 이어 쓴다. */
    FILE *fp = fopen("battle_log.txt", "a");

    /* 작업의 성공 여부를 저장한다. 이 예제에서는 1이 성공, 0이 실패이다. */
    int ok;

    /* 파일 열기가 실패했다면 포인터를 사용하지 않고 오류를 처리한다. */
    if (fp == NULL)
    {
        /* 실패한 파일 이름과 현재 시스템 오류 설명을 stderr에 표시한다. */
        perror("battle_log.txt");

        /* 이 사용자 정의 함수의 실패를 호출한 곳에 알리고 실행을 끝낸다. */
        return 0;
    }

    /* 한 사건을 한 줄로 쓰고 결과를 검사한다. */
    ok = fprintf(fp, "%s\n", event) >= 0;

    /* 앞 단계가 실패했으면 결과를 사용하지 않고 실패를 알린다. */
    if (!ok)
    {
        /* 쓰기 실패를 보고한다. */
        fputs("Log write failed.\n", stderr);
    }

    /* 파일을 닫고 결과를 확인한다. 이 호출 뒤 fp를 다시 사용하지 않는다. */
    if (fclose(fp) == EOF)
    {
        /* 작업 결과나 오류 안내 문구를 지정한 출력 통로로 보낸다. */
        fputs("Log close failed.\n", stderr);

        /* 작업 실패를 기억하여 나중에 성공했다고 안내하지 않도록 한다. */
        ok = 0;
    }

    /* 읽기/쓰기와 닫기 결과를 모은 성공 여부를 호출한 곳에 돌려준다. */
    return ok;
}

/* -------------------------------------------------------------------------
 * 역할: 지금까지 저장한 로그를 화면에 보여 준다.
 * 입력: 없음. void는 인자가 없다는 뜻이다.
 * 반환: 읽기와 출력 및 닫기가 성공하면 1, 실패하면 0.
 * 순서: "r"로 열기 → 한 줄 읽고 출력하기 반복 → 오류 확인 → 닫기.
 * ------------------------------------------------------------------------- */
static int show_log(void)
{
    /* 기존 파일을 읽기 전용으로 연다. */
    FILE *fp = fopen("battle_log.txt", "r");

    /* 한 줄을 읽을 배열이다. */
    char line[128];

    /* 일단 성공으로 시작하고, 오류를 발견하면 0으로 바꾼다. */
    int ok = 1;

    /* 파일 열기가 실패했다면 포인터를 사용하지 않고 오류를 처리한다. */
    if (fp == NULL)
    {
        /* 실패한 파일 이름과 현재 시스템 오류 설명을 stderr에 표시한다. */
        perror("battle_log.txt (record first)");

        /* 이 사용자 정의 함수의 실패를 호출한 곳에 알리고 실행을 끝낸다. */
        return 0;
    }

    /* 읽기에 성공한 줄만 처리한다. */
    while (fgets(line, sizeof line, fp) != NULL)
    {
        /* 읽은 문자열을 화면에 출력한다. 출력 오류이면 반복을 멈춘다. */
        if (fputs(line, stdout) == EOF)
        {
            /* 작업 실패를 기억하여 나중에 성공했다고 안내하지 않도록 한다. */
            ok = 0;

            /* 가장 가까운 반복문을 끝내고 반복문 다음으로 이동한다. */
            break;
        }
    }

    /* 입출력 오류 표시가 있는지 확인한다. 정상적인 파일 끝과 구분한다. */
    if (ferror(fp))
    {
        /* 작업 결과나 오류 안내 문구를 지정한 출력 통로로 보낸다. */
        fputs("Log read failed.\n", stderr);

        /* 작업 실패를 기억하여 나중에 성공했다고 안내하지 않도록 한다. */
        ok = 0;
    }

    /* 파일을 닫고 결과를 확인한다. 이 호출 뒤 fp를 다시 사용하지 않는다. */
    if (fclose(fp) == EOF)
    {
        /* 작업 결과나 오류 안내 문구를 지정한 출력 통로로 보낸다. */
        fputs("Log close failed.\n", stderr);

        /* 작업 실패를 기억하여 나중에 성공했다고 안내하지 않도록 한다. */
        ok = 0;
    }

    /* 읽기/쓰기와 닫기 결과를 모은 성공 여부를 호출한 곳에 돌려준다. */
    return ok;
}

/* -------------------------------------------------------------------------
 * 프로그램의 출발점이다. 위쪽에 함수 정의가 있어도 실행은 main에서 시작한다.
 * 필요한 함수를 호출하고, 그 함수가 return하면 호출한 곳의 다음 문장으로 돌아온다.
 * 메뉴형 예제에서는 파일 작업 실패를 안내한 뒤 다시 메뉴를 선택할 수 있다.
 * 마지막 EXIT_SUCCESS / EXIT_FAILURE는 운영체제에 전달할 종료 결과이다.
 * ------------------------------------------------------------------------- */
int main(void)
{
    panel("ADVENTURE JOURNAL / 10-01"); // 실습 제목이다.
    /* 메뉴 번호이다. */
    int choice;

    /* break 또는 return을 만날 때까지 반복한다. */
    for (;;)
    {
        /* 안내 문구와 최대 메뉴 번호를 넘기고 선택한 정수를 받는다. */
        panel("QUEST BOARD | Choose your next action"); // 사건과 메뉴를 구분한다.
        puts("  [1] Sword strike    [2] Collect 20 gold"); // 사건 선택이다.
        puts("  [3] Open journal    [0] Leave camp"); // 조회와 종료이다.
        choice = read_choice("  Action > ", 3);

        /* 0은 종료 메뉴이며 -1은 입력 종료/오류이므로 메뉴 반복을 끝낸다. */
        if (choice <= 0)
        {
            /* 가장 가까운 반복문을 끝내고 반복문 다음으로 이동한다. */
            break;
        }

        /* 작업의 성공 여부를 저장한다. 이 예제에서는 1이 성공, 0이 실패이다. */
        int ok;

        /* 메뉴 1번을 선택한 경우의 작업을 실행한다. */
        if (choice == 1)
        {
            /* 공격 사건을 문자열로 넘겨 파일 끝에 추가한다. */
            ok = append_event("[ATTACK] Hero dealt 10 damage to Slime.");
        }

        /* 메뉴 2번을 선택한 경우의 작업을 실행한다. */
        else if (choice == 2)
        {
            /* 보상을 기록한다. */
            ok = append_event("[LOOT] Hero obtained 20 gold.");
        }
        else
        {
            /* 전체 기록을 읽는다. */
            panel("BATTLE HISTORY"); // 전투 일지 구역이다.
            ok = show_log();
        }

        /* 앞 단계가 실패했으면 결과를 사용하지 않고 실패를 알린다. */
        if (!ok)
        {
            /* 작업 결과나 오류 안내 문구를 지정한 출력 통로로 보낸다. */
            fputs("Operation failed; you may retry.\n", stderr);
        }
    }

    /* 입출력 오류 표시가 있는지 확인한다. 정상적인 파일 끝과 구분한다. */
    if (ferror(stdin) != 0 || ferror(stdout) != 0)
    {
        /* 운영체제에 프로그램이 실패로 종료되었음을 알린다. */
        return EXIT_FAILURE;
    }

    /* 운영체제에 프로그램이 정상 종료되었음을 알린다. */
    return EXIT_SUCCESS;
}
