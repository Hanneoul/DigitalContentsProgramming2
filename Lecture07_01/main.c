/*
================================================================================
 [강의 자료] 포인터 복습: 문자열 포인터와 배열 주소 포인터 실습
================================================================================
* char[] vs const char* 의 메모리 동작 및 수정 가능 여부 확인

[1] char str[] = "Hello";  (문자 배열 선언)
- 스택(Stack) 영역에 6바이트(H, e, l, l, o, \0) 크기의 공간을 직접 확보함.
- 배열의 각 칸에 들어있는 문자 값을 직접 수정할 수 있음 (str[0] = 'h' 가능).

[스택(Stack) 메모리]
   +---+---+---+---+---+----+
   |'H'|'e'|'l'|'l'|'o'|'\0'|  <-- str 이라는 이름의 배열 (수정 가능!)
   +---+---+---+---+---+----+
   0x100 0x101 ...     0x105

[2] const char *str = "Hello";  (문자열 포인터 선언)
 - "Hello"라는 문자열은 읽기 전용 데이터(ROData) 영역에 할당됨.
 - 포인터 변수 str은 스택 영역에 생성되며, 문자열의 시작 주소(0x500)를 가리킴.
 - 문자열 내용을 직접 수정하려 하면 프로그램이 강제 종료됨 (str[0] = 'h' 불가능!).
 - 대신 str이 다른 문자열 주소를 가리키도록 변경하는 것은 가능함 (str = "World" 가능!).

   [스택(Stack) 메모리]                     [코드/상수(ROData) 메모리]
   +------------+                           +---+---+---+---+---+----+
   |   0x500    | ------------------------> |'H'|'e'|'l'|'l'|'o'|'\0'|
   +------------+                           +---+---+---+---+---+----+
   str (포인터 변수)                         0x500 (읽기 전용 영역)

================================================================================
*/

#include <stdio.h>

int main(void)
{
    // =========================================================================
    // PART 1: 문자열 저장 방식의 차이 (char 배열 vs char 포인터)
    // =========================================================================
    printf("=== PART 1: 문자열과 포인터 ===\n");

    // 1-1. char 배열 형태
    // 스택 영역에 6바이트 공간을 잡고 "Apple"을 복사해 넣음.
    char arrayStr[] = "Apple";

    // 1-2. char 포인터 형태
    // 상수 영역(ROData)에 "Banana"를 두고, 그 시작 주소를 ptrStr에 저장함.
    // C++ 호환성 및 안전성을 위해 const 키워드를 붙이는 것이 표준 권장사항임.
    const char* ptrStr = "Banana";

    printf("1. 초기 문자열 출력\n");
    printf("   arrayStr : %s (주소: %p)\n", arrayStr, (void*)arrayStr);
    printf("   ptrStr   : %s (주소: %p)\n\n", ptrStr, (void*)ptrStr);

    // 1-3. 내용 수정 테스트
    arrayStr[0] = 'a'; // 가능! 스택 메모리의 'A'를 'a'로 변경함.
    printf("2. arrayStr 첫 글자 수정 후: %s\n", arrayStr);

    // ptrStr[0] = 'b'; // [주의] 이 코드는 실행 중 프로그램이 강제 종료됨! (읽기 전용 메모리 접근)

    // 1-4. 가리키는 대상(주소) 변경 테스트
    // arrayStr = "Orange"; // [불가] 배열 이름은 주소 상수이므로 통째로 대입 불가능!
    ptrStr = "Orange";      // [가능!] 포인터 변수이므로 새로 생성된 "Orange"의 주소로 변경됨.
    printf("3. ptrStr가 가리키는 문자열 변경 후: %s (새 주소: %p)\n\n", ptrStr, (void*)ptrStr);


    return 0;
}