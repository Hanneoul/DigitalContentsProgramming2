/*
================================================================================
 [강의 자료] 1차원 배열(1D Array)의 이해와 활용: 1D 텍스트 RPG 맵
================================================================================

 1. 배열(Array)이란 무엇인가?
   - 동일한 자료형(Data Type)의 변수들을 메모리상에 연속적으로 배치한 데이터 구조임.
   - 단일 변수가 상자 하나라면, 배열은 상자들이 일렬로 연결된 '아파트'와 같음.
   - 예: char map[10]; -> 문자를 저장할 수 있는 공간 10개를 연속으로 할당함.

 2. 인덱스(Index)의 개념과 주의점 (★ 매우 중요)
   - 배열의 요소에 접근하기 위해 사용하는 번호를 '인덱스'라고 함.
   - C 언어에서 인덱스는 항상 '0'부터 시작함 (Zero-based Indexing).
   - 크기가 N인 배열의 유효한 인덱스 범위는 0부터 (N - 1)까지임.
   - 경계 초과(Out of Bounds) 주의:
     - char map[10]의 인덱스는 0, 1, 2, ..., 9까지 존재함.
     - map[10]에 접근하려고 하면 프로그램이 강제 종료되거나 undefined behavior(정의되지 않은 동작)가 발생함.
     - 플레이어 이동 구현 시 반드시 0 이상, (N - 1) 이하인지 경계 검사를 수행해야 함.

 3. 문자열과 문자 배열 (Null 문자 '\0')
   - C 언어에서 큰따옴표("")로 감싼 문자열은 끝에 눈에 보이지 않는 종료 문자 '\0'(Null Character)이 들어감.
   - 따라서 문자열 형태로 printf("%s", map); 조회를 하려면 배열 크기를 (원하는 칸 수 + 1)로 선언해야 함.
   - 예: 10칸짜리 맵을 printf("%s")로 출력하려면 char map[11]로 선언하고 map[10] = '\0'을 넣어야 함.

 4. 이동 로직의 원리 (선 삭제 후 이동)
   - 플레이어 '0'이 한 칸 이동하려면 다음 2단계를 거침:
     ① 현재 위치(playerPos)의 배열 값을 빈 공간('.')으로 원복.
     ② 입력받은 방향으로 인덱스를 변경(playerPos - 1 또는 + 1).
     ③ 새로운 위치(playerPos)의 배열 값을 플레이어('0')로 갱신.
================================================================================
*/

#include <stdio.h>
#include <conio.h>  // _getch() 함수 사용 (키보드 입력을 엔터 없이 바로 받기 위함)

#define MAP_SIZE 10 // 맵의 크기를 상수로 정의 (유지보수가 쉬워짐)

int main(void)
{
    
    // 맵 배열 선언 (출력을 위해 Null 문자를 포함하도록 MAP_SIZE + 1 크기로 할당)
    char map[MAP_SIZE + 1];

    // 플레이어의 현재 X 위치 (인덱스 0부터 시작)
    int playerPos = 0;

    // 키보드 입력을 저장할 변수
    char input = 0;

    // 1. 맵 초기화 (모든 칸을 '.'으로 채움)
    for (int i = 0; i < MAP_SIZE; i++)
    {
        map[i] = '.';
    }
    // 문자열 출력을 위해 배열의 마지막 위치에 Null 문자('\0') 추가
    map[MAP_SIZE] = '\0';

    // 게임 루프 (플레이어가 'q'를 누를 때까지 반복)
    while (1)
    {
        system("cls");
        // 2. 현재 플레이어 위치 업데이트
        map[playerPos] = '0';

        // 3. 화면 렌더링 (현재 맵 상태 출력)
        // system("cls"); // 화면을 깨끗이 지우고 싶다면 주석 해제 (Windows 환경)
        printf("\n=== 1D RPG MAP ===\n");
        printf("%s\n", map);
        printf("이동: [a] 왼쪽 | [d] 오른쪽 | [q] 종료\n");
        printf("입력: ");

        // 4. 키보드 입력 받기 (엔터 키 없이 즉시 입력)
        input = _getch();

        // 종료 조건 체크
        if (input == 'q' || input == 'Q')
        {
            printf("\n게임을 종료함.\n");
            break;
        }

        // 5. 이전 플레이어 위치 지우기 (지우지 않으면 이동 경로에 '0'이 남아있음)
        map[playerPos] = '.';

        // 6. 입력에 따른 위치 변경 및 배열 경계 검사 (Boundary Check)
        if (input == 'a' || input == 'A') // 왼쪽 이동
        {
            // 인덱스가 0보다 클 때만 왼쪽으로 이동 허용 (배열 왼쪽 밖으로 나가는 것 방지)
            if (playerPos > 0)
            {
                playerPos--;
            }
            else
            {
                printf("\n[경고] 왼쪽 벽에 부딪혔음!\n");
            }
        }
        else if (input == 'd' || input == 'D') // 오른쪽 이동
        {
            // 인덱스가 (MAP_SIZE - 1)보다 작을 때만 오른쪽 이동 허용
            if (playerPos < MAP_SIZE - 1)
            {
                playerPos++;
            }
            else
            {
                printf("\n[경고] 오른쪽 벽에 부딪혔음!\n");
            }
        }
    }

    return 0;
}