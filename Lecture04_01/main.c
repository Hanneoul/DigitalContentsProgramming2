/*
================================================================================
 [포인터(Pointer) 핵심 개념 및 기반 지식]
================================================================================
 1. 메모리(RAM)와 주소(Address)
	- 컴퓨터 메모리는 데이터를 저장하는 거대한 '상자들의 연속'임.
	- 각 상자(1 바이트 단위)마다 고유한 번지수가 부여되어 있는데, 이를 '주소(Address)'라 함.
	- 변수는 이 메모리 공간에 붙인 '이름표'이며, 주소는 그 위치의 '실제 좌표'임.

 2. & 연산자 (주소 연산자 / Address Operator)
	- 변수 이름 앞에 '&'를 붙이면 해당 변수가 메모리의 '몇 번지(주소)'에 위치하는지 추출함.
	- 예: &mySecretNum -> mySecretNum 변수가 위치한 메모리 주소값

 3. 포인터 변수 (Pointer Variable)
	- 주소값(Address) 자체를 저장하기 위해 선언하는 특별한 변수임.
	- 선언 방식: [데이터 타입]* [변수명];  (예: int* map;)
	- 포인터의 타입(int*, char* 등)은 "이 주소로 찾아갔을 때 몇 바이트 단위로
	  데이터를 읽어 들일 것인가"를 결정하는 '렌즈/돋보기' 역할을 함.

 4. * 연산자 (역참조 연산자 / Dereference Operator)
	- 포인터 변수 앞에 '*'를 붙이면, 해당 포인터가 가리키고 있는 '주소로 직접 찾아가서'
	  그 안에 들어있는 실제 데이터를 읽거나 수정함.
	- 예: *map -> map에 저장된 주소로 가서 실제 int 값을 꺼내옴.

 5. void* (범용/무형 포인터 / Void Pointer)
	- '타입 정보가 없는 pure한 메모리 주소'만을 저장하는 만능 주소 저장소임.
	- 어떤 타입의 주소(int*, double*, char* 등)든 제약 없이 모두 저장 가능함.
	- [주의] 타입 정보가 없으므로 컴퓨터가 몇 바이트를 읽어야 할지 알 수 없음.
	  따라서 `*secretMap`처럼 직접 역참조하는 것은 불가능하며,
	  반드시 명시적 형변환(Casting)을 통해 타입을 지정해 준 뒤 읽어야 함.

 6. 포인터 형변환 (Pointer Type Casting)
	- 형태: (변환할 포인터 타입)주소
	- 메모리 주소에 "이 데이터를 어떻게 해석할 것인가"라는 '렌즈'를 씌우는 작업임.
	- 예: (int*)secretMap -> secretMap 주소를 "int(4byte 정수)형 주소"로 해석하라는 의미.
================================================================================
*/

#include <stdio.h>

int main()
{
	// [1] 원본 데이터 생성
	int mySecretNum = 77; // 4바이트 정수형 변수 mySecretNum을 선언하고 77로 초기화함.

	// 변수에 저장된 실제 값(77)을 %d 형식 지정자로 출력함.
	printf("비밀번호 : %d \n", mySecretNum);

	// & 연산자를 사용하여 mySecretNum 변수가 할당된 실제 메모리 주소값을 %p(Pointer) 형식으로 출력함.
	printf("비밀번호의 주소 : %p \n", &mySecretNum);


	printf("---------------------------------\n");

	// [2] int* 포인터 변수를 활용한 데이터 가리키기
	int* map; // int형 변수의 주소를 저장할 수 있는 포인터 변수 map을 선언함.
	map = &mySecretNum; // map 변수에 mySecretNum의 메모리 주소값(&)을 대입함.

	// *map (역참조): map이 가리키는 주소로 찾아가서 그곳에 저장된 실제 정수값(77)을 읽어옴.
	printf("map에서 읽은 비밀번호 : %d \n", *map);

	// map 자체를 출력: map에 저장되어 있는 주소값(&mySecretNum과 동일한 주소)을 출력함.
	printf("map에서 읽은 비밀번호의 주소 : %p \n", map);

	printf("---------------------------------\n");

	// [3] 원본 변수의 값 변경 시 포인터의 동작 확인
	mySecretNum = 7; // 원본 변수의 값을 77에서 7로 변경함. (메모리 주소는 변경되지 않음)

	// map은 여전히 동일한 메모리 주소를 가리키고 있으므로, 변경된 값 7이 출력됨.
	printf("map에서 읽은 비밀번호 : %d \n", *map);

	// 메모리 주소 자체는 변하지 않고 그대로 유지됨을 확인함.
	printf("map에서 읽은 비밀번호의 주소 : %p \n", map);

	printf("---------------------------------\n");

	// [4] void* (무형 포인터)와 즉석 형변환(Casting)
	void* secretMap; // 타입 정보가 없는 만능 포인터 변수 secretMap을 선언함.
	secretMap = &mySecretNum; // void*는 어떤 타입의 주소든 암묵적으로 저장 가능함.

	// *(int*)secretMap:
	// 1. (int*)secretMap -> secretMap(void*)을 "int* 형 주소"로 명시적 형변환(Casting)함.
	// 2. *(int*)secretMap -> 캐스팅되어 int*가 된 주소를 역참조(*)하여 4바이트 정수값(7)을 읽어옴.
	// ※ 단순히 *secretMap 으로만 쓰면 몇 바이트를 읽을지 몰라 컴파일 에러가 발생함!
	printf("비밀map에서 읽은 비밀번호 : %d \n", *(int*)secretMap);

	// secretMap에 저장된 순수 메모리 주소값을 출력함 (%p).
	printf("비밀map에서 읽은 비밀번호의 주소 : %p \n", secretMap);

	// [5] void*를 int* 변수에 형변환하여 대입 후 활용
	int* intMap; // int형 주소를 전용으로 담을 포인터 변수 intMap 선언.
	intMap = (int*)secretMap; // void* 타입인 secretMap을 (int*)로 형변환하여 intMap에 대입함.

	// intMap은 이미 int* 타입이므로 추가 형변환 없이 *intMap 만으로 값을 안전하게 읽어옴.
	printf("int형 변환map에서 읽은 비밀번호 : %d \n", *intMap);

	return 0; // 프로그램 정상 종료
}