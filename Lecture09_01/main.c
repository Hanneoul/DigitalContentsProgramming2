/* ==========================================================================
 * [컴퓨터의 메모리 : RAM(Random Access Memory)에서 하드디스크까지]
 *
 * 프로그램이 실행될 때 사용하는 모든 변수와 데이터는 RAM(메모리)이라는 초고속 임시 숙소에 살고 있다.
 * 하지만 RAM은 전원이 꺼지거나 프로그램이 종료되면 모든 데이터가 허공으로 증발해 버리는 휘발성 공간이다.
 *
 * 코딩의 결과물이나 데이터를 영원히 보존하려면 전원이 꺼져도 끈질기게 기억을 붙잡고 있는
 * 하드디스크나 SSD라는 영원의 창고로 데이터를 보내야 한다.
 * 이 영원의 창고에 의미 있는 데이터 단위로 이름을 붙여 저장해 둔 것이 바로 파일(File)이다.
 * ==========================================================================
 *
 * [FILE 구조체와 버퍼(Buffer)]
 *
 * 하드디스크는 생각보다 엄청나게 느린 장치다. 프로그램이 데이터를 찔끔찔끔 보낼 때마다
 * 디스크에 직접 찾아가서 기록하면 속도가 터지게 느려진다.
 *
 * 그래서 C언어는 메모리(RAM)와 하드디스크 사이에 임시 바구니(버퍼)를 둔다.
 * 프로그램이 데이터를 쏟아부으면 이 바구니에 차곡차곡 모아두었다가,
 * 바구니가 꽉 차거나 파일을 닫을 때(fclose) 한꺼번에 하드디스크로 왕창 밀어 넣는 방식이다.
 *
 * 이 임시 바구니와 파일의 현재 상태(몇 번째 글자를 읽고 있는지 등)를 관리하기 위해
 * C언어가 만들어 둔 관리 대장이 바로 FILE 구조체다.
 * fopen은 "이 파일과 대화할 관리 대장을 내놓아라" 하고 요청하는 함수다.
 *
 *
 * [헤더 파일의 정체 : stdio.h와 stdlib.h는 무엇을 하는 녀석인가 ? ]
 *
 * C언어 코드를 보면 맨 위에 `#include <stdio.h>`와 `#include <stdlib.h>`가 항상 등장함.
 * 이 둘은 각각 고유한 임무를 가진 표준 라이브러리 헤더 파일임.
 *
 * 1. #include <stdio.h> (Standard Input / Output)
 * -이름 그대로 '표준 입출력'을 담당함.
 * -키보드로 입력받고(`scanf`), 화면에 출력하는(`printf`) 기능뿐만 아니라,
 *  이번 학습의 핵심인 * *파일 입출력(`fopen`, `fclose`, `fprintf` 등) * *의 모든 함수 원형과
 *  핵심 구조체인 `FILE`이 이 헤더 안에 정의되어 있음.파일을 다룰 때 필수적임.
 *
 * 2. #include <stdlib.h> (Standard Library)
 * -범용 유틸리티 함수들을 모아놓은 집합임.
 * -동적 메모리 할당(`malloc`, `free`), 난수 생성, 정수 변환, 그리고 프로그램 강제 종료(`exit`)나
 *  에러 상태를 알리는 기능 등을 제공함.
 * -파일 열기에 실패했을 때 프로그램을 안전하게 종료하거나 일반적인 유틸리티 기능을 쓸 때 함께 포함됨.
 * ==========================================================================
 *
 * [FILE 구조체 : 파일의 모든 것을 기록하는 관리 대장]
 *
 * C언어에서 `FILE`은 기본 자료형이 아니라, 컴파일러가 정의해 둔 커다란 구조체(struct)임.
 * 프로그램이 `fopen()`을 호출하는 순간, 운영체제는 하드디스크의 파일을 열고 그 파일에 대한 모든 상태 정보를
 * 담은 `FILE` 구조체 인스턴스를 메모리(HEAP 영역 등)에 생성한 뒤 그 주소(`FILE * `)를 반환함.
 *
 *`FILE` 구조체 내부에는 대략 다음과 같은 핵심 정보들이 들어있음 :
 * 1. 파일 디스크립터(File Descriptor) : 운영체제(OS)가 이 파일을 식별하기 위해 부여한 고유한 정수 번호.
 * 2. 입출력 버퍼(Buffer) 포인터 : 디스크와 직접 소통하면 속도가 느리므로, 메모리에 임시로 마련해 둔
 *                                 데이터 바구니의 주소, 현재 채워진 양, 남은 용량 등의 정보.
 * 3. 파일 오프셋(Position Indicator) : 현재 파일의 몇 번째 바이트를 읽고 쓰는지 가리키는 커서 위치.
 * 4. 상태 및 에러 플래그 : 파일의 끝(EOF)에 도달했는지, 혹은 읽기 / 쓰기 도중 에러가 발생했는지 기록하는 변수.
 *
 * 즉, 개발자는 복잡한 운영체제의 내부 메커니즘을 직접 제어할 필요 없이,
 * ========================================================================== */

#include <stdio.h>
#include <stdlib.h>

int main(void) {
    // 1. 하드디스크에 "test.txt" 파일을 쓰기(Write, "w") 목적으로 연다.
    FILE* fp = fopen("test.txt", "w");

    if (fp == NULL) {
        printf("파일 열기 실패\n");
        return 1;
    }

    // 2. 모니터에 출력하는 printf 대신, FILE 포인터(fp)에게 전달하는 fprintf를 사용한다.
    fprintf(fp, "파일에 저장되는 간단한 테스트 텍스트\n");

    // 3. 파일을 닫는다. 이 순간 메모리 버퍼에 남아있던 데이터가 하드디스크에 완전히 기록된다.
    fclose(fp);

    printf("파일 저장 완료\n");
    return 0;
}