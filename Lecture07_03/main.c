/*
================================================================================
 [강의 자료] 배열을 함수로 넘길 때 일어나는 비밀: "진짜 아파트 vs 주소 메모지"
================================================================================

 1. 왜 main()에서의 sizeof와 함수 안에서의 sizeof 결과가 다를까?
   - main() 함수 안의 arr  : 방 16개짜리 '진짜 아파트 건물' 그 자체임.
   - func() 함수 안의 arg : 건물 전체를 통째로 옮길 수 없어서 '아파트 주소가 적힌 종이 메모지'만 전달받은 것임.

 2. 초간단 비유로 이해하기 (아파트 vs 주소 메모지)
   - 친구에게 16층짜리 아파트를 보여주고 싶다고 해서 아파트 건물을 통째로 들어서 전달할 수는 없음.
   - 대신 아파트 위치가 적힌 '주소 메모지' 하나만 쥐여주는 것임.
   - main()에서 건물 크기를 재면 -> 아파트 전체 크기 (16칸 × 4바이트 = 64바이트)
   - func()에서 받은 걸 재면 -> '주소 메모지' 자체의 종이 크기 (64비트 컴퓨터에서는 주소값이 8바이트)

 3. C 언어의 핵심 규칙: 배열 쇠퇴 (Array Decay)
   - C 언어에서는 함수 매개변수로 배열 형태(`int arg[16]`)를 적어두어도,
     컴파일러가 이를 자동으로 '포인터 변수'(`int *arg`)로 바꿔버림.
   - 즉, `[16]`이라고 써둔 숫자는 컴파일러가 완전히 무시함 (`int arg[]`나 `int *arg`와 완전히 똑같음).
   - 따라서 함수 내부에서 `sizeof(arg)`를 실행하면 배열 전체 크기가 아니라,
     주소값을 담는 포인터 변수 자체의 크기(8바이트)가 측정되는 것임.

 4. 해결책: 함수에 배열을 넘길 때는 '개수(크기)'도 함께 전달해야 함!
   - 함수 안에서는 주소만 받기 때문에 이 배열이 몇 칸짜리인지 알 방법이 없음.
   - 따라서 항상 `void func(int *arg, int size)` 처럼 배열의 칸 수를 알려주는
     변수를 함께 넘겨주는 것이 올바른 C 언어 프로그래밍 작성법임.
================================================================================
*/

#include <stdio.h>

// 함수 선언부
// 매개변수에 int arg[16]이라고 썼지만, 실제로는 int *arg (포인터 변수)로 변환됨.
void func(int arg[16])
{
    printf("\n--- func() 함수 내부 --- \n");
    // arg는 배열이 아니라 주소값을 가진 포인터 변수임.
    // 64비트 환경에서 포인터 변수의 크기는 항상 8바이트임.
    printf("func() 안의 sizeof(arg) : %d 바이트 (배열 크기가 아니라 '주소 메모지' 크기!)\n", (int)sizeof(arg));
}

// 올바른 함수 구현 예시 (배열의 크기를 별도 매개변수로 전달받음)
void printArray(int* arg, int size)
{
    printf("\n--- printArray() 함수 내부 (올바른 전달 방식) --- \n");
    printf("전달받은 배열 요소 개수: %d개\n", size);
    for (int i = 0; i < size; i++)
    {
        printf("%d ", arg[i]);
    }
    printf("\n");
}

int main(void)
{
    // int(4바이트) 형태의 공간 16개를 스택 메모리에 실제로 생성함. (진짜 건물)
    int arr[16] = { 0 };

    printf("=== main() 함수 내부 ===\n");
    // arr은 실제 16개 정수 배열이므로 4바이트 * 16개 = 64바이트가 나옴.
    printf("main() 안의 sizeof(arr) : %d 바이트 (진짜 아파트 건물 전체 크기)\n", (int)sizeof(arr));

    // func 함수 호출 (arr 배열의 시작 주소값만 전달됨)
    func(arr);

    // 올바른 활용법: 배열의 실제 요소 개수를 계산해서 함께 전달함
    int arrayLength = sizeof(arr) / sizeof(arr[0]); // 64 / 4 = 16개
    printArray(arr, arrayLength);

    return 0;
}