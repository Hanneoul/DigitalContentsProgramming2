/*
================================================================================
 [강의 자료] static 스토리지와 정적 변수의 비밀
================================================================================

 1. static의 어원과 의미
 - static은 영어로 고정된, 정적인, 움직이지 않는다는 뜻임.
 - 프로그램이 실행되는 동안 메모리에서 위치가 바뀌지 않고 제자리를 묵묵히 지킨다고 해서 static이라는 이름이 붙었음.

 2. 왜 static이 생겼고 왜 필요할까?
 - 일반 지역 변수는 함수가 끝나면 스택에서 사라짐. 값을 유지하고 싶어서 전역 변수를 쓰면 프로그램 전체에서 접근할 수 있어 위험함.
 - 함수 내부에서만 은밀하게 접근할 수 있으면서도, 함수가 끝나도 값이 사라지지 않고 끝까지 살아남는 변수가 필요했음.
 - 이 두 가지 장점을 동시에 잡기 위해 static 변수가 탄생함.

 3. static 지역 변수의 핵심 특징 3가지
 ① 생명주기: 프로그램이 시작될 때 메모리에 딱 한 번 만들어지고, 프로그램이 종료될 때까지 영원히 살아남음. (스택의 포스트잇이 아니라 힙이나 데이터 영역처럼 오래 감)
 ② 유효범위: 변수가 선언된 그 함수 안에서만 접근할 수 있음. 외부 함수에서는 그 변수의 존재를 모름.
 ③ 초기화: 코드가 여러 번 실행되더라도 초기화 문장은 최초 딱 한 번만 실행되고 무시됨.

 4. 게임 비유로 이해하기: 던전의 누적 처치 카운터
 - 플레이어가 던전에 들어가서 몬스터를 잡을 때마다 몇 마리를 잡았는지 기록하고 싶음.
 - 함수가 끝날 때마다 기록이 사라지면 안 되므로, static 변수를 두어 함수가 몇 번 호출되든 처치 횟수가 차곡차곡 쌓이게 만듦.

================================================================================
 [강의 자료] 전역 변수와 정적 변수를 왜 굳이 따로 구분해서 만들었을까?
================================================================================

 1. 캡슐화와 정보 은닉 (Information Hiding)
 - 전역 변수는 프로그램 어디서든 접근할 수 있어 편하지만, 코드가 커지면 "도대체 어느 파일의
   어떤 함수가 이 값을 바꾼 거야?"를 추적하기 지옥같이 어려워짐. (전역 변수의 공포)
 - 반면 정적 변수는 "이 변수는 오직 이 함수(또는 이 파일) 안에서만 쓸 거야!"라며
   접근 범위를 엄격하게 제한(은닉)하기 위해 만들어짐.

 2. 이름 충돌 방지 (Namespace Pollution)
 - 프로젝트를 여러 명이서 개발하거나 파일이 수백 개로 늘어나면, 전역 변수 이름이
   중복되는 대참사가 벌어짐. (예: 양쪽 파일 다 player_count라는 이름을 쓸 때)
 - 파일 내부 전적 변수(file-scope static)나 함수 안의 정적 변수를 쓰면,
   이름이 같아도 서로 완전히 다른 공간으로 격리되므로 충돌 걱정이 사라짐.

 3. 메모리 수명과 유효범위의 분리 (Lifecycle vs Scope)
 - 지역 변수 : 함수가 끝나면 죽음 (수명 짧음) / 그 함수 안에서만 접근 가능 (범위 좁음)
 - 전역 변수 : 프로그램 끝날 때까지 안 죽음 (수명 김) / 어디서든 접근 가능 (범위 넓음)
 - 정적 변수 : 프로그램 끝날 때까지 안 죽음 (수명 김) -> 전역 변수의 장점
               하지만 선언된 그 함수 안에서만 접근 가능 (범위 좁음) -> 지역 변수의 장점
 - 즉, "오 오래 살았으면 좋겠는데, 남들이 함부로 건드리진 못하게 숨겨두고 싶다"는
   개발자의 까다로운 요구를 해결하기 위해 정적 변수가 분리되어 탄생한 것임.
================================================================================
*/

#include <stdio.h>

// 몬스터 처치 기록을 남기는 함수
void huntMonster(void)
{
    // 일반 지역 변수 (함수가 끝날 때마다 새로 만들어지고 0으로 초기화됨)
    int normalCount = 0;

    // static 지역 변수 (프로그램 실행 시 딱 한 번만 0으로 초기화되고, 함수가 끝나도 값이 보존됨)
    static int staticCount = 0;

    normalCount++;
    staticCount++;

    printf("일반 변수 count: %d (함수가 끝나면 증발함)\n", normalCount);
    printf("정적 staticCount: %d (함수가 끝나도 값이 유지됨!)\n", staticCount);
}

int main(void)
{
    printf("=== static 스토리지 실습 시작 ===\n\n");

    printf("1번째 몬스터 사냥:\n");
    huntMonster();

    printf("\n2번째 몬스터 사냥:\n");
    huntMonster();

    printf("\n3번째 몬스터 사냥:\n");
    huntMonster();

    // [참고] staticCount는 huntMonster 함수 안에서만 선언되었으므로 
    // main 함수에서 직접 접근하려고 하면 컴파일 에러가 발생함.
    // printf("%d", staticCount); -> 에러! 외부에서 접근 불가한 은밀한 변수임.

    return 0;
}