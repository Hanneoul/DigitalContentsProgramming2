/*
================================================================================
 [강의 자료] 포인터 복습: 문자열 포인터와 배열 주소 포인터 실습
================================================================================

[1] int arr[3] = {10, 20, 30};
 - 스택 메모리에 정수 3개(12바이트)를 연속으로 할당함.
 - arr 자체는 배열의 시작 주소(0x200)를 의미하지만, '주소 값을 담는 변수'가 아니라 '배열의 이름(상수)'임.
 - 따라서 arr = NULL 이나 arr++ 같은 연산이 불가능함.

   [스택(Stack) 메모리]
   +------+------+------+
   |  10  |  20  |  30  |  <-- arr (시작 주소: 0x200)
   +------+------+------+
   0x200  0x204  0x208


[2] int *ptr = arr;  (또는 int *ptr = &arr[0];)
 - ptr은 주소 값을 저장할 수 있는 4바이트 또는 8바이트 크기의 별도 포인터 변수임.
 - ptr에 arr(0x200)을 대입하면, ptr을 통해 arr의 요소들에 접근할 수 있음 (*ptr, ptr[1] 등).
 - ptr은 '변수'이므로 ptr++ 연산을 통해 주소를 한 칸(int 크기인 4바이트)씩 이동시킬 수 있음.

   [스택(Stack) 메모리]
   +------------+                           +------+------+------+
   |   0x200    | ------------------------> |  10  |  20  |  30  |
   +------------+                           +------+------+------+
   ptr (포인터 변수)                         arr[0]  arr[1] arr[2]
                                            0x200  0x204  0x208

---------------------------------------------------------------------------------*/

#include <stdio.h>

int main()
{
    // =========================================================================
   // PART 2: 정수형 배열과 포인터 연산
   // =========================================================================
    printf("=== PART 2: 정수 배열과 포인터 연산 ===\n");

    int numbers[3] = { 10, 20, 30 };

    // 배열의 이름(numbers)은 배열의 첫 번째 요소의 주소(&numbers[0])와 동일함.
    int* pNum = numbers; // int *pNum = &numbers[0]; 과 완벽히 동일함.

    printf("1. 배열 이름과 포인터가 가리키는 주소 비교\n");
    printf("   numbers 배열 시작 주소 : %p\n", (void*)numbers);
    printf("   pNum 포인터가 가진 주소: %p\n\n", (void*)pNum);

    printf("2. 포인터를 통한 배열 요소 접근 방식 3가지\n");
    // 방식 A: 배열 인덱스 표기법 (numbers[i])
    printf("   [방식 A] numbers[1]   = %d\n", numbers[1]);

    // 방식 B: 포인터 변수에 인덱스 사용 (pNum[i])
    printf("   [방식 B] pNum[1]      = %d\n", pNum[1]);

    // 방식 C: 포인터 간접 참조 연산 (*(pNum + i))
    // pNum + 1 은 단순 1 바이트 추가가 아니라, sizeof(int)인 4바이트만큼 뒤의 주소를 의미함.
    printf("   [방식 C] *(pNum + 1)  = %d\n\n", *(pNum + 1));

    printf("3. 포인터 증감 연산(pNum++)을 이용한 배열 순회\n");
    for (int i = 0; i < 3; i++)
    {
        // *pNum : 현재 pNum이 가리키는 위치의 값을 가져옴
        // pNum  : 현재 포인터가 들고 있는 메모리 주소
        printf("   [Index %d] 주소: %p | 값: %d\n", i, (void*)pNum, *pNum);

        // 포인터를 다음 요소 위치로 이동 (int 타입이므로 주소값이 4씩 증가함)
        pNum++;
    }

    return 0;
}
