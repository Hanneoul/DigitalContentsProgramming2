/*
================================================================================
 [파일 이름] main.c
 [설명] 프로그램이 시작되는 곳이며, game.c에 있는 변수를 extern으로 가져다 씀.

 [실습 3] 멀티 파일 시뮬레이션: 다른 파일(다른 소스코드)에 있는 전역 변수를 가져다 쓰는 상황
 - 실제 변수의 실물(정의)은 이 아래나 혹은 다른 파일에 존재함
 - 다른 파일(game.c)에 저 이름의 전역 변수가 실제로 존재한다고 컴파일러에 알려줌.
 - 새로운 공간을 만드는 게 아니라 다른 곳에 있는 메모리를 같이 쓰겠다는 선언임.
================================================================================
*/


#include <stdio.h>

extern int g_playerScore;
extern int g_stageLevel;

// game.c에 있는 함수를 쓰기 위해 선언함
void updateGameData(void);

int main(void)
{
    printf("=== 멀티 파일 extern 예제 시작 ===\n");

    // 다른 파일에서 선언된 변수를 내 것처럼 편하게 읽어 씀
    printf("현재 스테이지: %d\n", g_stageLevel);
    printf("초과된 플레이어 점수: %d\n", g_playerScore);

    // 다른 파일에 있는 함수를 호출해서 변수를 조작함
    updateGameData();

    // 함수 실행 후 변수 값이 실제로 변경되었는지 확인함
    printf("함수 실행 후 플레이어 점수: %d\n", g_playerScore);

    return 0;
}