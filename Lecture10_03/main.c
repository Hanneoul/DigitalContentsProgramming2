/*
==============================================================================
 [강의 자료] Lecture10_03 | 몬스터 도감 | 슬라임 밸런스 패치
==============================================================================

1. 오늘의 게임 장면
    슬라임 HP 30을 90으로 바꾸려고 매번 다시 빌드해야 할까?
    게임 규칙은 C 코드에, 몬스터 수치는 텍스트 파일에 나누어 둔다.

       monsters.txt                Monster 배열
       Slime 30 5 10  --읽기-->  [0] Slime / 30 / 5 / 10
       Goblin 60 12 25           [1] Goblin / 60 / 12 / 25
    Data(데이터)는 처리할 값이다. 코드가 요리법이면 데이터는 재료이다.

 2. 한 줄이 몬스터 한 마리
    이름 HP 공격력 골드 순서이다. 이름에는 영문만 사용한다.
    fgets는 크기를 지키며 줄을 읽고 strtol은 문자열을 long으로 바꾼다.
    끝 포인터는 숫자 뒤의 남은 글자 위치이다. 추가 글자도 검사한다.
    errno의 ERANGE와 허용 범위를 검사하여 너무 큰 숫자를 걸러낸다.
    배열은 0번부터 시작한다. count는 읽은 수, 용량은 최대 8마리이다.

 3. 깨진 도감은 입장 금지
    한 줄이라도 잘못되면 전체 적용을 중단한다.
    빈 파일, 9마리, 음수 HP, 추가 열도 실패이다.
    UTF-8 BOM 없는 텍스트로 저장한다. 제공 파일은 ASCII이다.

 4. 작은 실험과 답
    Slime의 30만 90으로 수정 → 빌드 없이 재실행 → HP=90 확인.
    90을 abc로 바꾸면? 답: 해당 줄 오류와 함께 실패한다.
    실습 뒤에는 제공된 30으로 되돌린다.

 5. 코드 지도
    main의 읽기 → parse_monster 검증 → 배열 저장 → 도감 출력.
    읽기 반복과 배열 출력을 작성한다. 숫자 변환 검사는 제공 코드이다.

 [공통 메모]
 파일은 실행 작업 폴더(VS에서는 프로젝트 폴더)에 생성된다.
 바이너리 구조체 저장은 동일 빌드 환경용이며 필드 변경 시 재생성한다.
 제공된 입력 검사보다 파일 처리 함수부터 읽는다. 실패 안내도 실행 결과이다.

==============================================================================
 [실습 코드] 먼저 실행 → 예측 → 추가 부분 작성 → 다시 실행
==============================================================================
*/

/* errno와 ERANGE로 변환 오류를 확인한다. */
#include <errno.h>

/* 파일 및 표준 입출력 함수를 선언한다. */
#include <stdio.h>
#include "../LectureSupport/console.h" // 공통 화면 도구이다.

/* 표준 종료 코드 EXIT_SUCCESS, EXIT_FAILURE를 사용한다. */
#include <stdlib.h>

/* 문자열 길이 및 문자 검색 함수를 사용한다. */
#include <string.h>

/* 배열의 최대 몬스터 수이다. */
#define MAX_MONSTERS 8

/* 몬스터 한 마리의 자료형이다. */
typedef struct Monster
{
    /* 슬롯 이름을 보관한다. */
    char name[20];

    /* 현재 체력이다. */
    int hp;

    /* 공격력을 보관한다. */
    int attack;

    /* 소지 골드이다. */
    int gold;
} Monster;

/* -------------------------------------------------------------------------
 * 역할: 숫자처럼 보이는 글자를 실제 정수로 바꾸고 범위를 확인한다.
 * 입력: text = 숫자 문자열, minimum = 최솟값, result = 숫자를 넣을 변수의 주소.
 * 반환: 성공 1 / 실패 0. 변환한 실제 숫자는 *result에 별도로 넣는다.
 * 예: parse_number("30", 1, &hp)는 성공 시 hp에 30을 넣고 1을 반환한다.
 * ------------------------------------------------------------------------- */
static int parse_number(const char *text, int minimum, int *result)
{
    /* 해석이 끝난 위치를 받는다. */
    char *end;

    /* strtol 결과의 자료형이다. */
    long value;

    /* 이전 작업의 오류 번호를 지워 이번 숫자 변환의 범위 오류를 구분한다. */
    errno = 0;

    /* 10진수로 해석한다. */
    value = strtol(text, &end, 10);

    /* long이 담을 수 있는 범위를 벗어난 숫자는 거부한다. */
    if (errno == ERANGE)
    {
        /* 숫자 변환 실패를 호출한 곳에 알린다. */
        return 0;
    }

    /* 해석 종료 위치가 시작 위치와 같으면 숫자를 한 글자도 읽지 못했다. */
    if (end == text)
    {
        /* abc처럼 숫자로 시작하지 않는 입력이다. */
        return 0;
    }

    /* 숫자 뒤에 문자가 남아 있으면 30x처럼 잘못된 입력이다. */
    if (*end != '\0')
    {
        /* 문자열 전체가 숫자여야 하므로 거부한다. */
        return 0;
    }

    /* 숫자 변환에 성공해도 게임이 허용한 최솟값과 최댓값을 지켜야 한다. */
    if (value < minimum || value > 9999)
    {
        /* 게임 규칙에 맞지 않는 값은 결과 변수에 넣지 않는다. */
        return 0;
    }

    /* 검사가 끝난 숫자를 int로 바꿔 호출자가 준 주소에 넣는다. */
    *result = (int)value;

    /* 모든 검사를 통과했으므로 호출한 곳에 성공을 알린다. */
    return 1;
}

/* -------------------------------------------------------------------------
 * 역할: 한 줄을 이름, 체력, 공격력, 골드로 나눈다.
 * 입력: line = 파일에서 읽은 한 줄, monster = 결과를 담을 구조체의 주소.
 * 반환: 네 항목이 모두 올바르면 1, 형식이나 값이 잘못되면 0.
 * 문자열 추출 → 항목 개수/길이 확인 → 이름 확인 → 숫자 세 개 확인 순서이다.
 * ------------------------------------------------------------------------- */
static int parse_monster(const char *line, Monster *monster)
{
    char hp[32];
    char attack[32];
    char gold[32];

    /* 추가 열을 검사할 문자이다. */
    char extra;

    /* 네 필드를 먼저 문자열로 읽고, 다섯 번째 문자가 있으면 추가 항목으로 탐지한다. */
    int fields =
        sscanf(line, "%19s %31s %31s %31s %c", monster->name, hp, attack, gold, &extra);

    /* 정확히 네 항목을 얻지 못했다면 이 줄은 사용할 수 없다. */
    if (fields != 4)
    {
        /* 이 사용자 정의 함수의 실패를 호출한 곳에 알리고 실행을 끝낸다. */
        return 0;
    }

    /* 폭 제한에 걸린 숫자를 다음 필드로 잘못 나누지 않도록 긴 숫자를 거부한다. */
    if (strlen(hp) == 31 || strlen(attack) == 31 || strlen(gold) == 31)
    {
        /* 이 사용자 정의 함수의 실패를 호출한 곳에 알리고 실행을 끝낸다. */
        return 0;
    }
    if (strspn(monster->name, "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz") !=
        strlen(monster->name))
    {
        /* 이 사용자 정의 함수의 실패를 호출한 곳에 알리고 실행을 끝낸다. */
        return 0;
    }

    /* 해당 숫자 변환이 실패하면 몬스터 한 줄 전체를 거부한다. */
    if (parse_number(hp, 1, &monster->hp) == 0)
    {
        /* 이 사용자 정의 함수의 실패를 호출한 곳에 알리고 실행을 끝낸다. */
        return 0;
    }

    /* 해당 숫자 변환이 실패하면 몬스터 한 줄 전체를 거부한다. */
    if (parse_number(attack, 0, &monster->attack) == 0)
    {
        /* 이 사용자 정의 함수의 실패를 호출한 곳에 알리고 실행을 끝낸다. */
        return 0;
    }

    /* 해당 숫자 변환이 실패하면 몬스터 한 줄 전체를 거부한다. */
    if (parse_number(gold, 0, &monster->gold) == 0)
    {
        /* 이 사용자 정의 함수의 실패를 호출한 곳에 알리고 실행을 끝낸다. */
        return 0;
    }

    /* 모든 검사를 통과했으므로 호출한 곳에 성공을 알린다. */
    return 1;
}

/* -------------------------------------------------------------------------
 * 프로그램의 출발점이다. 위쪽에 함수 정의가 있어도 실행은 main에서 시작한다.
 * 필요한 함수를 호출하고, 그 함수가 return하면 호출한 곳의 다음 문장으로 돌아온다.
 * 메뉴형 예제에서는 파일 작업 실패를 안내한 뒤 다시 메뉴를 선택할 수 있다.
 * 마지막 EXIT_SUCCESS / EXIT_FAILURE는 운영체제에 전달할 종료 결과이다.
 * ------------------------------------------------------------------------- */
int main(void)
{
    panel("MONSTER BESTIARY / 10-03"); // 실습 제목이다.
    /* 외부 데이터를 연다. */
    FILE *fp = fopen("monsters.txt", "r");

    /* 몬스터 배열을 초기화한다. */
    Monster monsters[MAX_MONSTERS] = {0};

    /* 배열 크기를 표현하는 부호 없는 정수형으로 개수를 센다. */
    size_t count = 0;

    /* 오류 위치를 알릴 줄 번호이다. */
    size_t line_number = 0;

    /* 한 줄을 읽을 배열이다. */
    char line[128];

    /* 일단 성공으로 시작하고, 오류를 발견하면 0으로 바꾼다. */
    int ok = 1;

    /* 파일 열기가 실패했다면 포인터를 사용하지 않고 오류를 처리한다. */
    if (fp == NULL)
    {
        /* 실패한 파일 이름과 현재 시스템 오류 설명을 stderr에 표시한다. */
        perror("monsters.txt");

        /* 운영체제에 프로그램이 실패로 종료되었음을 알린다. */
        return EXIT_FAILURE;
    }

    /* 읽기에 성공한 줄만 처리한다. */
    while (fgets(line, sizeof line, fp) != NULL)
    {
        /* 줄 번호를 증가시킨다. */
        ++line_number;
        if (strlen(line) > 126 || count == MAX_MONSTERS ||

            /* 길이와 용량을 먼저 검사한다. */
            !parse_monster(line, &monsters[count]))
        {
            /* 형식 문자열의 % 자리에 값을 넣어 지정한 통로에 출력한다. */
            fprintf(stderr, "Invalid data at line %zu (length, capacity, or format).\n",

                    /* 문제 위치를 알린다. */
                    line_number);

            /* 작업 실패를 기억하여 나중에 성공했다고 안내하지 않도록 한다. */
            ok = 0;

            /* 가장 가까운 반복문을 끝내고 반복문 다음으로 이동한다. */
            break;
        }

        /* 완전한 몬스터만 센다. */
        ++count;
    }

    /* 입출력 오류 표시가 있는지 확인한다. 정상적인 파일 끝과 구분한다. */
    if (ferror(fp))
    {
        /* 작업 결과나 오류 안내 문구를 지정한 출력 통로로 보낸다. */
        fputs("Monster read failed.\n", stderr);

        /* 작업 실패를 기억하여 나중에 성공했다고 안내하지 않도록 한다. */
        ok = 0;
    }

    /* 파일을 닫고 결과를 확인한다. 이 호출 뒤 fp를 다시 사용하지 않는다. */
    if (fclose(fp) == EOF)
    {
        /* 작업 결과나 오류 안내 문구를 지정한 출력 통로로 보낸다. */
        fputs("Monster close failed.\n", stderr);

        /* 작업 실패를 기억하여 나중에 성공했다고 안내하지 않도록 한다. */
        ok = 0;
    }
    if (count == 0)
    {
        /* 작업 결과나 오류 안내 문구를 지정한 출력 통로로 보낸다. */
        fputs("Monster file is empty or invalid.\n", stderr);

        /* 작업 실패를 기억하여 나중에 성공했다고 안내하지 않도록 한다. */
        ok = 0;
    }

    /* 앞 단계가 실패했으면 결과를 사용하지 않고 실패를 알린다. */
    if (!ok)
    {
        /* 운영체제에 프로그램이 실패로 종료되었음을 알린다. */
        return EXIT_FAILURE;
    }

    /* 읽은 개수만큼 순회한다. */
    for (size_t i = 0; i < count; ++i)
    {
        /* 현재 데이터를 지정한 형식에 맞추어 화면에 표시한다. */
        puts("  +----------------------------------------+"); // 카드 테두리이다.
        printf("  %-12s HP=%d ATK=%d GOLD=%d\n", monsters[i].name, monsters[i].hp,

               /* 수치를 출력한다. */
               monsters[i].attack, monsters[i].gold);
    }

    /* 입출력 오류 표시가 있는지 확인한다. 정상적인 파일 끝과 구분한다. */
    if (ferror(stdout) != 0)
    {
        /* 운영체제에 프로그램이 실패로 종료되었음을 알린다. */
        return EXIT_FAILURE;
    }

    /* 운영체제에 프로그램이 정상 종료되었음을 알린다. */
    return EXIT_SUCCESS;
}
