{
    /* 이름 배열 안에 문자열 끝 표시가 있는지 확인하여 배열 밖 읽기를 막는다. */
    if (memchr(p->name, '\0', sizeof p->name) == NULL)
    {
        /* 이 사용자 정의 함수의 실패를 호출한 곳에 알리고 실행을 끝낸다. */
        return 0;
    }

    /* 저장 데이터의 해당 값이 이 예제에서 정한 허용 범위에 있는지 확인한다. */
    if (p->name[0] == '\0')
    {
        /* 이 사용자 정의 함수의 실패를 호출한 곳에 알리고 실행을 끝낸다. */
        return 0;
    }

    /* 저장 데이터의 해당 값이 이 예제에서 정한 허용 범위에 있는지 확인한다. */
    if (p->level < 1 || p->level > 99)
    {
        /* 이 사용자 정의 함수의 실패를 호출한 곳에 알리고 실행을 끝낸다. */
        return 0;
    }

    /* 저장 데이터의 해당 값이 이 예제에서 정한 허용 범위에 있는지 확인한다. */
    if (p->hp < 0 || p->hp > 100)
    {
        /* 이 사용자 정의 함수의 실패를 호출한 곳에 알리고 실행을 끝낸다. */
        return 0;
    }

    /* 저장 데이터의 해당 값이 이 예제에서 정한 허용 범위에 있는지 확인한다. */
    if (p->gold < 0 || p->gold > 9999)
    {
        /* 이 사용자 정의 함수의 실패를 호출한 곳에 알리고 실행을 끝낸다. */
        return 0;
    }

    /* 모든 검사를 통과했으므로 호출한 곳에 성공을 알린다. */
    return 1;
}

/* 이어하기에 필요한 상태 전체를 묶는다. */
typedef struct GameState
{
    /* 캐릭터 구조체를 멤버로 포함한다. */
    Player player;

    /* 진행 스테이지이다. */
    int stage;

    /* 일차원 맵에서의 위치이다. */
    int position;

    /* 유일한 상자의 개봉 여부이다. */
    int chest_opened;
} GameState;

/* -------------------------------------------------------------------------
 * 역할: 캐릭터와 월드 진행 값이 모두 유효한지 확인한다.
 * 입력: game = 검사할 GameState의 주소. 이 함수는 내용을 바꾸지 않는다.
 * 반환: 캐릭터, 스테이지, 위치, 상자 상태가 모두 정상일 때만 1.
 * valid_player를 호출해 이미 만든 캐릭터 검사 기능을 다시 사용한다.
 * ------------------------------------------------------------------------- */
static int valid_game(const GameState *game)
{
    /* 캐릭터 검사 함수를 호출하여 플레이어 정보부터 확인한다. */
    if (valid_player(&game->player) == 0)
    {
        /* 이 사용자 정의 함수의 실패를 호출한 곳에 알리고 실행을 끝낸다. */
        return 0;
    }

    /* 저장 데이터의 해당 값이 이 예제에서 정한 허용 범위에 있는지 확인한다. */
    if (game->stage < 1 || game->stage > 10)
    {
        /* 이 사용자 정의 함수의 실패를 호출한 곳에 알리고 실행을 끝낸다. */
        return 0;
    }

    /* 저장 데이터의 해당 값이 이 예제에서 정한 허용 범위에 있는지 확인한다. */
    if (game->position < 0 || game->position > 90)
    {
        /* 이 사용자 정의 함수의 실패를 호출한 곳에 알리고 실행을 끝낸다. */
        return 0;
    }

    /* 저장 데이터의 해당 값이 이 예제에서 정한 허용 범위에 있는지 확인한다. */
    if (game->chest_opened != 0 && game->chest_opened != 1)
    {
        /* 이 사용자 정의 함수의 실패를 호출한 곳에 알리고 실행을 끝낸다. */
        return 0;
    }

    /* 모든 검사를 통과했으므로 호출한 곳에 성공을 알린다. */
    return 1;
}

/* -------------------------------------------------------------------------
 * 역할: 캐릭터와 월드 진행 상태를 하나의 저장 파일에 기록한다.
 * 입력: game = 현재 GameState의 주소.
 * 반환: 구조체 한 개 기록 및 닫기가 성공하면 1, 실패하면 0.
 * 골드뿐 아니라 상자 개봉 여부도 같은 객체에 들어 있어 함께 저장된다.
 * ------------------------------------------------------------------------- */
static int save_game(const GameState *game)
{
    /* 현재 상태로 기존 저장을 덮어쓴다. */
    FILE *fp = fopen("game.dat", "wb");

    /* 작업의 성공 여부를 저장한다. 이 예제에서는 1이 성공, 0이 실패이다. */
    int ok;

    /* 파일 열기가 실패했다면 포인터를 사용하지 않고 오류를 처리한다. */
    if (fp == NULL)
    {
        /* 실패한 파일 이름과 현재 시스템 오류 설명을 stderr에 표시한다. */
        perror("game.dat");

        /* 이 사용자 정의 함수의 실패를 호출한 곳에 알리고 실행을 끝낸다. */
        return 0;
    }

    /* 객체 한 개 전체를 기록한다. */
    ok = fwrite(game, sizeof *game, 1, fp) == 1;

    /* 앞 단계가 실패했으면 결과를 사용하지 않고 실패를 알린다. */
    if (!ok)
    {
        /* 쓰기 실패를 알린다. */
        fputs("Game write failed.\n", stderr);
    }

    /* 파일을 닫고 결과를 확인한다. 이 호출 뒤 fp를 다시 사용하지 않는다. */
    if (fclose(fp) == EOF)
    {
        /* 작업 결과나 오류 안내 문구를 지정한 출력 통로로 보낸다. */
        fputs("Game close failed.\n", stderr);

        /* 작업 실패를 기억하여 나중에 성공했다고 안내하지 않도록 한다. */
        ok = 0;
    }

    /* 읽기/쓰기와 닫기 결과를 모은 성공 여부를 호출한 곳에 돌려준다. */
    return ok;
}

/* -------------------------------------------------------------------------
 * 역할: 저장된 게임 전체를 복원한다.
 * 입력: game = 복원한 결과를 넣을 현재 GameState의 주소.
 * 반환: 읽기와 검사에 성공하면 1, 실패하면 0.
 * 실패 시 현재 상태를 유지하고, 성공 시 마지막 구조체 대입으로 함께 바꾼다.
 * ------------------------------------------------------------------------- */
static int load_game(GameState *game)
{
    /* 저장된 게임을 연다. */
    FILE *fp = fopen("game.dat", "rb");

    /* 불완전한 데이터는 임시 객체에만 받는다. */
    GameState temporary = {0};

    /* 작업의 성공 여부를 저장한다. 이 예제에서는 1이 성공, 0이 실패이다. */
    int ok;

    /* 파일 열기가 실패했다면 포인터를 사용하지 않고 오류를 처리한다. */
    if (fp == NULL)
    {
        /* 실패한 파일 이름과 현재 시스템 오류 설명을 stderr에 표시한다. */
        perror("game.dat (save first)");

        /* 이 사용자 정의 함수의 실패를 호출한 곳에 알리고 실행을 끝낸다. */
        return 0;
    }

    /* 전체 객체를 읽는다. */
    ok = fread(&temporary, sizeof temporary, 1, fp) == 1;

    /* 객체를 완전히 읽었을 때만 파일 뒤의 여분 데이터가 있는지 검사한다. */
    if (ok && fgetc(fp) != EOF)
    {
        /* 작업 실패를 기억하여 나중에 성공했다고 안내하지 않도록 한다. */
        ok = 0;
    }

    /* 입출력 오류 표시가 있는지 확인한다. 정상적인 파일 끝과 구분한다. */
    if (ferror(fp))
    {
        /* 작업 실패를 기억하여 나중에 성공했다고 안내하지 않도록 한다. */
        ok = 0;
    }

    /* 파일을 닫고 결과를 확인한다. 이 호출 뒤 fp를 다시 사용하지 않는다. */
    if (fclose(fp) == EOF)
    {
        /* 작업 실패를 기억하여 나중에 성공했다고 안내하지 않도록 한다. */
        ok = 0;
    }

    /* 읽기와 값 검사를 통과해야 한다. */
    if (!ok || !valid_game(&temporary))
    {
        /* 작업 결과나 오류 안내 문구를 지정한 출력 통로로 보낸다. */
        fputs("Invalid or unreadable save; current game unchanged.\n", stderr);

        /* 이 사용자 정의 함수의 실패를 호출한 곳에 알리고 실행을 끝낸다. */
        return 0;
    }

    /* 캐릭터와 월드 상태를 함께 복사한다. 이 줄 전까지 현재 게임은 유지된다. */
    *game = temporary;

    /* 모든 검사를 통과했으므로 호출한 곳에 성공을 알린다. */
    return 1;
}

/* -------------------------------------------------------------------------
 * 프로그램의 출발점이다. 위쪽에 함수 정의가 있어도 실행은 main에서 시작한다.
 * 필요한 함수를 호출하고, 그 함수가 return하면 호출한 곳의 다음 문장으로 돌아온다.
 * 메뉴형 예제에서는 파일 작업 실패를 안내한 뒤 다시 메뉴를 선택할 수 있다.
 * 마지막 EXIT_SUCCESS / EXIT_FAILURE는 운영체제에 전달할 종료 결과이다.
 * ------------------------------------------------------------------------- */
int main(void)
{
    panel("CONTINUE ADVENTURE / 10-04"); // 실습 제목이다.
    GameState game = {{"Hero", 1, 100, 0}, 1, 0, 0};

    /* break 또는 return을 만날 때까지 반복한다. */
    for (;;)
    {
        /* 메뉴 번호이다. */
        int choice;

        /* 현재 데이터를 지정한 형식에 맞추어 화면에 표시한다. */
        panel("WORLD STATUS | One chest, one reward"); // 상태 카드이다.
        track(game.stage - 1, 1); // 스테이지 위치를 그린다.
        puts(game.chest_opened ? "  [__] CHEST OPEN" : "  [##] CHEST CLOSED"); // 상자 그림이다.
        printf("  %s level=%d HP=%d gold=%d stage=%d position=%d chest=%d\n",
               game.player.name, game.player.level, game.player.hp, game.player.gold,

               /* 월드 상태를 전달한다. */
               game.stage, game.position, game.chest_opened);

        /* 안내 문구와 최대 메뉴 번호를 넘기고 선택한 정수를 받는다. */
        choice = read_choice("[1] Move | [2] Chest | [3] Save | [4] Load | [0] Exit > ", 4);

        /* 0은 종료 메뉴이며 -1은 입력 종료/오류이므로 메뉴 반복을 끝낸다. */
        if (choice <= 0)
        {
            /* 가장 가까운 반복문을 끝내고 반복문 다음으로 이동한다. */
            break;
        }

        /* 메뉴 1번을 선택한 경우의 작업을 실행한다. */
        if (choice == 1)
        {
            if (game.stage < 10)
            {
                ++game.stage;
                game.position += 10;
            }
            else
            {
                /* 더 이동할 수 없음을 알린다. */
                puts("Last stage reached.");
            }
        }

        /* 메뉴 2번을 선택한 경우의 작업을 실행한다. */
        else if (choice == 2)
        {
            if (game.chest_opened)
            {
                /* 작업 결과나 오류 안내 문구를 지정한 출력 통로로 보낸다. */
                puts("Chest already opened. No extra gold.");
            }
            else if (game.player.gold > 9799)
            {
                /* 허용 골드 범위를 검사한다. */
                puts("Gold limit reached.");
            }
            else
            {
                game.player.gold += 200;
                game.chest_opened = 1;
            }
        }

        /* 메뉴 3번을 선택한 경우의 작업을 실행한다. */
        else if (choice == 3)
        {
            /* 사용자 정의 함수를 호출하고 성공을 뜻하는 1일 때만 다음 안내를 실행한다. */
            if (save_game(&game))
            {
                /* 작업 결과나 오류 안내 문구를 지정한 출력 통로로 보낸다. */
                puts("Saved.");
            }
        }
        else
        {
            /* 사용자 정의 함수를 호출하고 성공을 뜻하는 1일 때만 다음 안내를 실행한다. */
            if (load_game(&game))
            {
                /* 작업 결과나 오류 안내 문구를 지정한 출력 통로로 보낸다. */
                puts("Loaded.");
            }
        }
    }

    /* 입출력 오류 표시가 있는지 확인한다. 정상적인 파일 끝과 구분한다. */
    if (ferror(stdin) != 0 || ferror(stdout) != 0)
    {
        /* 운영체제에 프로그램이 실패로 종료되었음을 알린다. */
        return EXIT_FAILURE;
    }

    /* 운영체제에 프로그램이 정상 종료되었음을 알린다. */
    return EXIT_SUCCESS;
}
