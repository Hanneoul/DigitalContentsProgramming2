/*
================================================================================
 [강의 자료] 스택(Stack) vs 힙(Heap) 메모리 철저 파헤치기
================================================================================

 1. 한눈에 보는 메모리 지도 (ASCII Memory Map)

  HIGH ADDRESS (높은 주소: 0xFFFFFFFF)
  +-------------------------------------------------------------+
  |                                                             |
  |  [ 스택 영역 (STACK) - 차곡차곡 정돈되어 쌓여있는것 ]       |
  |  - 특징: 위에서 아래로 메모리가 쌓임 (Downwards)            |
  |  - 용도: 지역 변수, 함수 매개변수                           |
  |  - 관리: 컴파일러가 알아서 자동 할당 / 자동 삭제            |
  |  - 성격: 칼같은 자취방 퇴실시간 (함수 끝나면 방 빼야 함!)   |
  |                                                             |
  |       |  int stackNum = 100;                                |
  |       v  (아래 방향으로 자람)                               |
  |                                                             |
  +-------------------------------------------------------------+
  |                       |  자유 공간                          |
  |                       v  (스택과 힙 사이)                   |
  +-------------------------------------------------------------+
  |                       ^                                     |
  |                       |  (위 방향으로 자람)                 |
  |                                                             |
  |  [ 힙 영역 (HEAP) - 정돈안된 무더기 ]                       |
  |  - 특징: 아래에서 위로 메모리가 늘어남 (Upwards)            |
  |  - 용도: 동적 할당 (malloc, calloc, ralloc 등)              |
  |  - 관리: 오직 '개발자(나)'만 관리할 수 있음                 |
  |  - 성격: 무단점거 가능 (free 안 해주면 계속 자리 차지함)    |
  |                                                             |
  |       malloc(sizeof(int)); --> 4바이트 대여!                |
  |                                                             |
  +-------------------------------------------------------------+
  |  [ 데이터 / 코드 영역 (Data / Code) ]                       |
  |  - 전역 변수, 정수형/문자열 상수, 실행할 프로그램 코드      |
  +-------------------------------------------------------------+
  LOW ADDRESS (낮은 주소: 0x00000000)


 2. 함수 호출 시 스택과 힙에서 벌어지는 일 (시각화)

  (1) createStackValue() 호출 시:
      [스택 메모리]
      +------------------------+
      | stackNum = 100         | <-- 만들어짐!
      +------------------------+
                  |
                  v  (함수 종료 순간!)
      [스택 메모리]
      +------------------------+
      | [ 지워짐 / 쓰레기값 ]  | <-- 펑! 하고 사라짐! 주소 넘겨줘봤자 꽝임.
      +------------------------+

  (2) createHeapValue() 호출 시:
      [스택 메모리]                   [힙 메모리]
      +------------------+           +------------------+
      | heapPtr (포인터) | --------> |  *heapPtr = 200  | <-- malloc으로 생성!
      +------------------+           +------------------+
               |                              |
               v (함수 종료)                  v (함수가 끝나도 살아있음!)
      [스택 메모리]                   [힙 메모리]
      | (heapPtr 변수 사라짐) |       |  200 (데이터 유지!) | <-- 개발자가 free 안 하면
                                                                   영원히 상주함!


 3. 초간단 3줄 요약
   ① 스택(Stack): "칼퇴근 책임자" -> 함수 끝나면 알아서 깔끔하게 싹 지워줌.
   ② 힙(Heap): "무법지대 사물함" -> 내가 `malloc`으로 빌리고 `free`로 반납 안 하면 영원히 차있음.
   ③ 댕글링 포인터(Dangling Pointer): 이미 지워진 스택 주소를 쳐다보고 있는 불쌍한 포인터.
================================================================================
*/

#include <stdio.h>
#include <stdlib.h> // malloc, free 함수 사용을 위한 헤더파일

// [스택의 한계를 보여주는 함수]
int* createStackValue(void)
{
    // 스택 영역에 4바이트 정수 변수 할당
    int stackNum = 100;

    printf("[Stack 함수] 내부 변수 값: %d (주소: %p)\n", stackNum, (void*)&stackNum);

    // [경고] stackNum은 이 함수가 끝나는 '}'를 만나는 순간 스택에서 증발함!
    // 지워질 예정인 메모리의 주소를 반환하는 것은 매우 위험한 짓임.
    return &stackNum;
}

// [힙의 유용함을 보여주는 함수]
int* createHeapValue(void)
{
    // 힙(Heap) 영역에 int 크기(4바이트)만큼 사물함을 대여함
    // malloc은 힙에 생성된 메모리의 시작 주소를 반환함
    int* heapPtr = (int*)malloc(sizeof(int));

    // 힙 메모리가 가득 찼거나 할당 실패 시 NULL 반환 예외 처리
    if (heapPtr == NULL)
    {
        printf("힙 메모리가 부족합니다!\n");
        return NULL;
    }

    // 힙 영역 공간에 값 200 대입 (* : 역참조 연산자)
    *heapPtr = 200;

    printf("[Heap  함수] 내부 변수 값: %d (주소: %p)\n", *heapPtr, (void*)heapPtr);

    // 힙에 만들어진 메모리 주소를 반환함.
    // 이 함수가 끝나서 스택이 정리되어도, 힙에 든 200은 절대로 안 사라짐!
    return heapPtr;
}

int main(void)
{
    printf("================ 1. 스택(Stack) 수명 테스트 ================\n");
    int* pStack = createStackValue();

    // createStackValue() 함수는 이미 끝났음.
    // pStack이 가리키던 메모리는 이미 파괴되었으므로 이상한 쓰레기값이 출력되거나 에러남.
    printf("[main  함수] pStack이 가리키는 값: %d (지워진 메모리 훔쳐보기)\n\n", *pStack);


    printf("================ 2. 힙(Heap) 수명 테스트 ================\n");
    int* pHeap = createHeapValue();

    // createHeapValue() 함수가 끝났어도, 힙에 있는 데이터는 당당하게 살아있음!
    printf("[main  함수] pHeap이 가리키는 값 : %d (안전하게 유지됨)\n", *pHeap);

    // ★ 힙 메모리의 골든 규칙: 쓰다 남았으면 제때 반납(free)하자!
    // free를 안 해주면 프로그램이 꺼질 때까지 메모리를 먹고 있는 '메모리 누수(Memory Leak)' 발생!
    free(pHeap);

    // 반납했으니 포인터에 NULL을 넣어 깔끔하게 입싹닦(=안전 처리) 해줌
    pHeap = NULL;

    printf("[main  함수] free() 반납 완료! 사물함 열쇠 정리 끝.\n");

    return 0;
}