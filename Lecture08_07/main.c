/*
================================================================================
 [강의 자료] 전역 객체와 정적 객체(변수)의 초기화 마스터하기
================================================================================

 1. 전역 변수와 정적 변수란 무엇인가?
 - 전역 변수는 프로그램 어디서든 접근할 수 있는 만인의 공유 자산임.
 - 정적 변수는 특정 함수나 파일 안에서만 접근할 수 있지만 프로그램이 끝날 때까지 살아남는 은밀한 자산임.
 - 이 둘은 공통적으로 스택이 아니라 데이터(Data) 영역이나 BSS 영역이라는 특별한 장소에 자리를 잡음.

 2. 초기화 규칙의 핵심 비밀 (C 언어의 철칙)
 - 전역 변수와 정적 변수는 반드시 '상수(Constant)'로만 초기화할 수 있음.
 - 예를 들어 int a = 10; 은 가능하지만, int a = getLevel(); 처럼 함수의 리턴값이나 다른 변수의 값으로 초기화하는 것은 C 언어에서 불가능함. (변수가 만들어지는 시점이 프로그램 시작 전이기 때문임)

 3. 명시적 초기화 vs 자동 0초기화 (BSS 영역의 마법)
 - 개발자가 값을 지정해주지 않으면, 컴퓨터는 이 변수들을 자동으로 0(포인터는 NULL)으로 깔끔하게 초기화해줌.
 - 지역 변수는 쓰레기 값이 들어있지만, 전역/정적 변수는 알아서 0으로 채워짐.

 4. 게임 비유로 이해하기
 - 전역 변수는 성 전체에 걸쳐 있는 '왕국의 금고'임. 누구나 열어볼 수 있음.
 - 정적 변수는 길드 사무실 구석에 박혀 있는 '길드장 전용 금고'임. 길드 사무실 안에서만 쓸 수 있지만 영원히 사라지지 않음.


================================================================================
* 추가 강의 자료 

1. 왜 전역/정적 변수는 초기화하지 않아도 자동으로 0이 될까?
- 지역 변수의 비밀 (스택 영역)
지역 변수는 함수가 실행될 때 스택(Stack)이라는 임시 공간에 만들어짐.
스택은 함수가 호출될 때마다 수없이 생겼다 사라지기를 반복하므로, 컴퓨터가 속도를 높이기 위해 메모리를 0으로 일일이 밀어주는 작업을 생략함. 그래서 이전에 다른 프로그램이 쓰다 버린 쓰레기 값이 그대로 남아있게 됨.

- 전역/정적 변수의 비밀 (데이터 & BSS 영역)
전역 변수와 정적 변수는 프로그램이 실행되기 전부터 컴파일 결과물(실행 파일)의 데이터(Data) 영역과 BSS 영역에 자리를 박고 앉음.
이 중 값을 따로 지정하지 않은 변수들이 들어가는 곳이 BSS 영역임. 운영체제(OS)가 이 실행 파일을 메모리에 적재할 때, BSS 영역에 할당된 공간은 운영체제가 통째로 0으로 싹 밀어버림(Zero-fill).
따라서 개발자가 값을 안 넣어줘도 운영체제 차원에서 무조건 0(포인터는 NULL)으로 깔끔하게 초기화해 주는 것임.

2. 왜 하필 '상수'로만 초기화할 수 있을까? (함수나 다른 변수 안 되는 이유)
- 초기화 시점의 문제
전역 변수와 정적 변수는 main 함수가 실행되기도 전에 이미 메모리에 자리를 잡고 값이 채워져 있어야 함.
프로그램이 실행되기 직전(OS가 메모리에 로드하는 단계)에 초기화가 완료되어야 하므로, 이 시점에는 아직 CPU가 코드를 한 줄도 실행하지 않은 상태임.

- 상수만 가능한 이유
아직 코드가 실행되지 않았기 때문에 다른 변수의 값을 읽어오거나(g_serverPort), 함수를 호출해서(printf) 그 리턴값을 집어넣는 동적인 연산을 할 수가 없음.
오직 컴파일할 때 값이 변하지 않는 상수(Constant)만 미리 바이너리 파일에 박아둘 수 있는 것임.

3. 정적 변수(Static)도 똑같을까?
- 100% 똑같음.
- 함수 안에 선언된 static int count = 0; 같은 정적 지역 변수도 겉모습만 특정 함수 안에서만 접근할 수 있도록 범위가 제한되어 있을 뿐, 실제 메모리는 전역 변수와 똑같이 데이터/BSS 영역에 만들어짐.
- 정적 변수 역시:
    a.프로그램 시작 전에 미리 0(또는 상수)으로 초기화됨.
    b.다른 변수나 함수의 리턴값으로 초기화하는 것은 불가능함.
    c.프로그램이 종료될 때까지 메모리에서 사라지지 않고 유지됨.
================================================================================
*/

#include <stdio.h>

// [1] 명시적 초기화가 된 전역 변수 (Data 영역에 저장됨)
int g_serverPort = 8080;
char g_serverName[20] = "RPG_World_Server";

// [2] 초기화를 하지 않은 전역 변수 (BSS 영역에 저장되며 컴퓨터가 자동으로 0으로 채워짐)
int g_totalUserCount;
double g_worldTimeRate;

// [★ 에러 케이스 주의] 
// 전역 변수나 정적 변수는 프로그램이 실행되기도 전(메모리에 올라갈 때)에 미리 값이 결정되어야 함.
// 따라서 아래처럼 다른 변수의 값이나 함수의 리턴값으로 초기화하려고 하면 컴파일 에러가 터짐!
// int g_errorTest = g_serverPort; // (에러!) 다른 전역 변수의 값으로 초기화 불가능
// int g_errorTest2 = printf("Hello"); // (에러!) 함수의 리턴값으로 초기화 불가능

// 몬스터 생성 관리 함수
void spawnMonster(void)
{
    // [3] 정적 지역 변수 (Data 영역에 저장되며 함수가 처음 호출될 때 딱 한 번만 초기화됨)
    // 일반 지역 변수와 달리 함수가 끝나도 값이 증발하지 않고 누적됨
    static int monsterSerialNo = 1000;

    monsterSerialNo++;
    printf("몬스터 소환! 고유 번호: #%d\n", monsterSerialNo);
}

int main(void)
{
    printf("=== 전역 및 정적 객체 초기화 실습 시작 ===\n\n");

    // 명시적으로 초기화한 전역 변수 확인
    printf("서버 이름: %s\n", g_serverName);
    printf("서버 포트: %d\n\n", g_serverPort);

    // 초기화하지 않은 전역 변수가 정말 0으로 자동 세팅되었는지 확인
    printf("초기화 안 한 유저 수 (자동 0 세팅): %d\n", g_totalUserCount);
    printf("초기화 안 한 시간 배율 (자동 0 세팅): %.2f\n\n", g_worldTimeRate);

    // 정적 변수 초기화 테스트 (함수를 여러 번 호출해보기)
    printf("--- 정적 변수 누적 테스트 ---\n");
    spawnMonster();
    spawnMonster();
    spawnMonster();

    return 0;
}