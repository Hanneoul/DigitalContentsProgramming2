/*
================================================================================
 [강의 자료] extern 스토리지와 변수 공유
================================================================================

 1. extern의 어원과 의미
 - extern은 영어 단어 external(외부의)의 줄임말임.
 - 직역하면 '외부에 있는 것을 가져다 쓴다'는 뜻임.
 - 내 방(현재 파일)에 없거나 다른 방(다른 파일)에 있는 변수를 빌려 쓰겠다는 의미임.

 2. 왜 extern이 생겼고 왜 필요할까?
 - 프로그램이 커지면 코드를 파일 하나에 다 담지 못하고 여러 개로 쪼갬.
 - A 파일에 만든 중요한 전역 변수를 B 파일에서도 똑같이 쓰고 싶을 때가 생김.
 - 이때 B 파일에 똑같은 변수를 또 선언하면 메모리가 낭비되고 각각 다른 값을 가지게 됨.
 - 진짜 변수는 다른 곳에 있으니 그 변수를 같이 공유해서 쓰라고 알려주는 도구가 바로 extern임.

 3. 함수보다 변수를 아래에 선언하면 왜 에러가 날까?
 - C 언어 컴파일러는 코드를 위에서 아래로 한 줄씩 순차적으로 읽어 내려감.
 - 함수가 위쪽에 있고 변수가 아래쪽에 있으면 컴파일러는 위를 읽을 때 아래에 무엇이 있는지 알지 못함.
 - 그래서 변수가 없다고 착각하고 컴파일 에러를 발생시킴.

 4. #include보다 먼저 전역 변수를 선언하면 안 되는 이유
 - #include는 지정한 헤더 파일의 내용을 그 자리에 그대로 복사해서 붙여넣는 전처리기 작업임.
 - 전역 변수를 헤더 파일보다 위에 선언하면 코드 전체의 컴파일 순서가 꼬이게 됨.
 - 헤더 파일 안의 내용이 전역 변수의 영향을 받거나 충돌을 일으켜 원인을 알 수 없는 버그가 발생함.
 - 그래서 항상 헤더 파일을 먼저 선언하고 그 아래에 변수나 함수를 배치해야 함.
================================================================================
*/
// [실습 2] #include보다 먼저 전역 변수를 선언하면 안 되는 이유
int g_gameMoney = 50000;

#include <stdio.h>

// [실습 1] 함수보다 아래에 있는 변수를 미리 알리기 위한 extern 선언
// 새로운 메모리 공간을 만드는 것이 아니라, 어디선가 만들어질 변수를 참조하겠다는 뜻임
extern int g_playerLevel;

void printPlayerStatus(void);

int main(void)
{
    printf("=== extern 스토리지 실습 시작 ===\n");

    // 선언이 위쪽에 존재하므로 아래에 정의된 변수를 에러 없이 가져다 쓸 수 있음
    printf("main 함수 안의 플레이어 레벨: %d\n", g_playerLevel);
    printf("main 함수 안의 게임 머니: %d\n", g_gameMoney);

    printPlayerStatus();

    return 0;
}

// =============================================================================
// 실제 변수의 실물(정의와 메모리 할당)은 함수보다 아래쪽에 위치함
// 만약 위에서 extern으로 미리 알려주지 않았다면 컴파일 에러가 발생함
// =============================================================================
int g_playerLevel = 99;

void printPlayerStatus(void)
{
    printf("\n[함수 호출] 외부 변수 참조 결과\n");
    printf("현재 레벨: %d\n", g_playerLevel);
    printf("현재 자산: %d원\n", g_gameMoney);
}