/*
================================================================================
[강의 자료] 자동 스토리지(Automatic Storage)와 스택(Stack)
================================================================================

 1. '자동 스토리지(Automatic Storage)'란 무엇이고 왜 그렇게 부를까?
   - C 언어에서 함수 안이나 코드 블록(`{ }`) 안에 선언한 일반 지역 변수의 life cycle을 의미한다.
   - '자동(Automatic)'이라고 부르는 이유는, 개발자가 직접 메모리를 만들고 지우는
     명령을 쓸 필요 없이, 컴퓨터가 변수가 필요해지는 순간(블록 진입)에 자동으로 만들고,
     볼 일 다 보면(블록 탈출) 알아서 흔적도 없이 지워버리기 때문임!
     (우리가 직접 방을 치우지 않고 로봇청소기가 알아서 해주는 것과 같음)

 2. 게임 비유로 이해하기: RPG 던전 입장과 퇴장
   - 플레이어가 평화로운 '마을'을 돌아다닐 때는 거대한 보스 데이터가 필요 없음.
   - 하지만 '보스 방(코드 블록 `{}`)에 입장하는 순간', 보스의 체력, 공격력 같은
     지역 변수들이 스택(Stack) 메모리에 촤라락 자동 소환됨!
   - 보스 방을 클리어하고 퇴장하는 순간(`}`를 만나는 순간), 보스 관련 변수들은
     스택에서 순식간에 팝(Pop)되면서 증발함. 메모리 관리가 아주 깔끔함.

 3. 스택(Stack)의 구조와 코드 블록(`{ }`)의 비밀
   - 스택은 급식실 식판이나 접시 쌓기와 같음. 먼저 들어간 게 맨 아래에 깔리고,
     나중에 들어간 게 맨 위에 쌓임(LIFO: Last-In, First-Out).
   - 코드 블록 `{ }`은 변수의 생명이 유지되는 '결계'임.
     중괄호 안에서 태어난 변수는 중괄호가 끝나는 순간 사망함.

 4. 왜 굳이 이 자동 스토리지를 쓸까? (이득과 장점)
   - 편의성: 매번 `malloc`하고 `free`할 필요가 없어서 코드가 엄청 편해짐.
   - 속도: 스택 메모리는 포인터 위치만 위아래로 움직이면 끝이라 할당 속도가 빛의 속도임.
   - 안전성: 함수나 블록이 끝나면 알아서 정리가 되니까 찌꺼기 데이터가 남지 않음.
================================================================================
*/

#include <stdio.h>

// 마을 함수
void enterVillage(void)
{
    printf("\n[마을 진입] 평화로운 마을임.\n");

    // 이 변수는 마을 함수에 진입하는 순간 스택에 자동으로 만들어짐 (자동 스토리지)
    int villageGold = 500;
    printf("마을 주머니 속 골드: %d\n", villageGold);

    // 이 함수가 끝나서 '}'를 만나는 순간 villageGold는 스택에서 흔적도 없이 사라짐!
}

// 던전 함수 (보스 방)
void enterBossDungeon(void)
{
    printf("\n[던전 입장] 거대한 보스 방에 들어왔음!\n");

    // 보스 방 안의 코드 블록 (미니 결계)
    {
        // 이 변수는 이 중괄호 안에서만 태어나는 임시 변수임
        int bossHp = 10000;
        printf("보스 등장! 보스 체력: %d\n", bossHp);

        bossHp -= 3000;
        printf("플레이어의 강력한 공격! 보스 잔여 체력: %d\n", bossHp);
    } // <-- 이 중괄호를 만나는 순간 bossHp는 스택에서 즉시 강제 사형(소멸)당함!

    // [참고] printf("%d", bossHp); <-- 여기서 bossHp를 쓰려고 하면 이미 죽은 변수라 에러가 남!
    printf("보스 방 블록을 탈출했으므로 bossHp 변수는 이미 증발했음.\n");
}

int main(void)
{
    printf("=== RPG 게임 시작 (자동 스토리지 시뮬레이터) ===\n");

    // 마을에 들어감 -> 변수가 스택에 쌓였다가 함수 끝나며 자동 삭제됨
    enterVillage();

    // 보스 던전에 들어감 -> 블록 안에서 변수들이 생겼다 사라지는 것을 반복함
    enterBossDungeon();

    // 다시 마을에 들어감 -> 이전 마을과 똑같은 변수 이름을 써도 스택의 다른 공간에 새로 만들어짐
    enterVillage();

    printf("\n게임 종료. 모든 스택 메모리는 컴퓨터가 알아서 깔끔하게 청소함.\n");
    return 0;
}