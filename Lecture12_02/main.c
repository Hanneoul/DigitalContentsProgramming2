/*
==============================================================================
 [강의 자료] Lecture12_02 | 콜백 전달 | 상자는 보상 방식을 모른다
==============================================================================

1. 오늘의 장면: 보물 상자의 보상 버튼
    01 함수 주소 보관 → 02 콜백 전달 → 03 콜백 등록·교체 → 04 객체와 사건 정보.
    같은 보상 함수를 유지하며 호출 책임을 조금씩 옮긴다.
    Callback은 call back, 요청받은 쪽이 지정된 함수를 되불러 주는 방식이다.
    함수 포인터는 주소를 담는 도구, 콜백은 그 도구를 쓰는 호출 방식이다.
    콜백은 비동기라는 뜻이 아니다. 이 예제는 모두 같은 흐름에서 즉시 호출한다.

 2. 함수 포인터 읽기
    void (*reward)(int) : int 하나를 받고 반환값이 없는 함수의 주소이다.
    void *reward(int)와 다르다. 별표와 이름을 괄호로 묶어야 함수 포인터이다.
    reward = AddGold; 는 주소를 보관한다. AddGold(20); 은 지금 호출한다.
    reward(20); 은 보관된 함수를 호출한다. (*reward)(20)도 같은 호출이다.
    대입할 함수의 반환형과 매개변수형을 일치시킨다. 억지 형변환은 하지 않는다.

 3. 01에서 추가할 것
    RewardCallback이라는 typedef와 OpenChest를 추가한다.
    main의 reward(20) 대신 OpenChest(AddGold)를 호출한다.
       main: 함수 선택 → OpenChest: 호출 시점 결정 → AddGold: 실제 보상
    상자 코드는 골드 계산을 알 필요가 없다. 버튼 클릭, 충돌, 작업 완료에 유용하다.
    NULL은 지정된 함수가 없다는 뜻이다. 검사 없이 호출하면 안 된다.
    예상: 상자 그림 두 번, 보상은 한 번, GOLD=20.
    실험: 두 번째 NULL도 AddGold로 바꾸면 GOLD=40이다.
    이 단계는 독립된 상자 열기 요청을 시연한다. 같은 상자의 중복 방지는 다음 단계이다.

==============================================================================
 [실습 코드] 먼저 실행 → 예측 → 추가 부분 작성 → 다시 실행
==============================================================================
*/

#include "../LectureSupport/console.h" // 화면 도구이다.
typedef void (*RewardCallback)(int); // [추가] 함수 포인터형에 이름을 붙인다.

int gold = 0; // 보상으로 쌓인 골드이다.

void AddGold(int amount) // 모든 단계에서 유지할 보상 함수이다.
{ // 보상 시작.
    gold += amount; // 받은 수량을 누적한다.
    printf("  REWARD +%d | GOLD=%d\n", amount, gold); // 결과를 표시한다.
} // 보상 끝.

void OpenChest(RewardCallback reward) // [추가] 할 일을 함수 주소로 전달받는다.
{ // 상자 처리 시작.
    puts("  [##] -> [__] CHEST OPEN"); // 상자가 열리는 장면이다.
    if (reward != NULL) reward(20); // 등록된 반응이 있을 때만 호출한다.
} // 상자 처리 끝.

int main(void) // 실행 시 반응을 전달한다.
{ // main 시작.
    panel("12-02 | PASS A CALLBACK"); // 제목이다.
    OpenChest(AddGold); // 함수 주소를 전달하고 상자가 콜백을 호출하게 한다.
    OpenChest(NULL); // 콜백 없는 동작도 허용하는지 확인한다.
    return 0; // 정상 종료이다.
} // main 끝.
