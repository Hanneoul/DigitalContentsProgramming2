 /* ==========================================================================
  * [fopen의 모든 것: 파일 오픈 모드(Mode)의 완벽 해부]
  *
  * C언어에서 파일을 열 때 사용하는 `fopen(const char *filename, const char *mode)` 함수는
  * 두 번째 인자인 `mode` 문자열에 따라 파일의 운명이 결정됨.
  * 모드는 크게 기본 모드(`r`, `w`, `a`), 수정/확장 모드(`+`), 그리고 파일 형식 모드(`b`)의 조합으로 이루어짐.
  *
  * 1. 기본 3대 모드 (Single Modes)
  *    - "r" (Read, 읽기 전용):
  *      * 파일을 읽기 목적으로 연다.
  *      * 파일이 반드시 존재해야 함. 파일이 없으면 `fopen`은 실패하고 `NULL`을 반환함.
  *    - "w" (Write, 쓰기/덮어쓰기 모드):
  *      * 파일을 쓰기 목적으로 연다.
  *      * 파일이 없으면 새로 생성하지만, **만약 파일이 이미 존재한다면 기존 내용을 전부 지워버리고(Truncate) 0바이트로 만듦**.
  *      * 즉, 기존 데이터를 날리고 새로 덮어쓸 때 사용함.
  *    - "a" (Append, 이어쓰기 모드):
  *      * 파일을 추가 쓰기 목적으로 연다.
  *      * 파일이 없으면 새로 생성함.
  *      * 파일이 이미 존재하면 기존 내용은 그대로 보존하고, 파일의 맨 마지막(EOF)에 새로운 데이터를 이어 붙임.
  *        파일 포인터를 어디로 옮기든 쓰기 연산은 무조건 파일 끝에만 수행됨.
  *
  * 2. 읽기/쓰기 복합 모드 (Update Modes: '+')
  *    - "r+": 읽기 및 쓰기 가능. 파일이 반드시 존재해야 하며, 기존 내용의 특정 위치를 수정(업데이트)할 때 쓴다.
  *      파일을 열 때 포인터가 맨 처음에 위치하므로, 그냥 쓰기를 하면 기존 글자가 덮어씌워짐.
  *    - "w+": 읽기 및 쓰기 가능. 파일이 없으면 생성하고, 있으면 내용을 전부 비운다(덮어쓰기 기반의 읽기/쓰기).
  *    - "a+": 읽기 및 이어쓰기 가능. 파일이 없으면 생성하며, 읽기는 파일 전체를 대상으로 자유롭게 할 수 있지만,
  *            쓰기 연산은 파일 포인터 위치와 무조건 상관없이 파일의 맨 끝(EOF)에만 강제로 추가됨.
  *
  *    [★ 중요: '+' 모드 사용 시 핵심 주의사항]
  *    - 읽기와 쓰기가 모두 가능하지만, 스트림의 읽기 작업과 쓰기 작업 사이 전환 시 반드시
  *      `fflush()`를 호출하거나 `fseek()`, `rewind()` 같은 파일 위치 이동 함수를 중간에 호출해야 함.
  *      (그렇지 않으면 C 표준상 버퍼 동기화 문제로 오작동이 발생함)
  *
  * 3. 형식 지정 모드 ('b' vs 텍스트 모드)와 저장 상태의 차이
  *    - 모드 문자열에 'b'를 붙이면(예: "rb", "wb", "ab+", "w+b", "r+b") **바이너리(Binary) 모드**로 동작함.
  *    - 텍스트 모드(기본값):
  *      * 운영체제별로 개행 문자를 다르게 처리함. 특히 Windows 환경에서는 텍스트 모드로 `\n`(LF)을 기록하면
  *        운영체제가 이를 자동으로 `\r\n`(CR+LF, 2바이트)로 변환해서 디스크에 저장함. 반대로 읽을 때는 `\r\n`을 `\n`으로 복원함.
  *      * 만약 텍스트 모드로 이미지나 압축파일 같은 바이너리 데이터를 읽고 쓰면, 특정 바이트 값(예: `0x0A`)이
  *        개행 문자로 오인되어 데이터가 변형되거나 깨지는 대참사가 발생함.
  *    - 바이너리 모드('b'):
  *      * 이러한 운영체제별 변환을 일체 거치지 않고, RAM에 있는 비트/바이트 그대로(1:1 매핑) 디스크에 밀어 넣거나 꺼냄.
  *      * 구조체 변수 통째로 쓰기(`fwrite`), 이미지 파일 처리, 네트워크 패킷 버퍼 저장 등에 필수적임.
  *
  * 4. 권한 위반 에러 조합과 잘못된 사용 (예: 읽기 전용 모드에서 `fprintf` 사용)
  *    - 파일을 "r"이나 "rb"(읽기 전용)로 열어놓고 `fprintf`나 `fputc` 같은 쓰기 함수를 호출하면 어떻게 될까?
  *    - 컴파일은 정상적으로 될 수 있으나, 실행 중에 해당 스트림이 쓰기 권한을 가지고 있지 않기 때문에
  *      내부적으로 에러 플래그(`ferror`)가 설정되거나 쓰기 연산이 무시됨.
  * ========================================================================== */

  /* ==========================================================================
   * [플러시(Flush)란 무엇인가? 버퍼를 강제로 비우는 기술]
   *
   * 1. 플러시(Flush)의 정의와 어원
   *    - 'Flush'의 사전적 의미는 화장실 물을 '내리다', 혹은 파이프에 물을 '쏴서 씻어내다'라는 뜻임.
   *    - 프로그래밍에서 플러시는 "메모리 버퍼(임시 바구니)에 쌓여 있는 데이터를 대기시키지 않고,
   *      목적지(하드디스크, 콘솔 화면 등)로 강제로 싹 밀어내어 비우는 작업"을 의미함.
   *
   * 2. fflush() 함수가 필요한 이유와 작동 원리
   *    - 앞에서 배웠듯 C언어는 속도 최적화를 위해 파일에 쓸 때 데이터를 곧바로 디스크에 기록하지 않고
   *      RAM의 출력 버퍼에 차곡차곡 모아둠.
   *    - 버퍼가 꽉 차거나, `fclose()`를 호출할 때, 혹은 프로그램이 정상 종료될 때 알아서 버퍼가 비워지지만
   *      때로는 **"지금 당장 버퍼에 있는 내용을 디스크 파일에 완전히 써 내려가게 만들고 싶다!"**는 상황이 발생함.
   *    - 이때 사용하는 함수가 바로 `int fflush(FILE *stream);`임.
   *    - 출력 스트림(쓰기 모드)에 `fflush(fp)`를 호출하면, 아직 디스크로 가지 못하고 메모리에 발이 묶여 있던
   *      데이터들이 즉시 하드디스크로 강제 송출되어 저장됨.
   *
   * 3. 주의사항: 입력 스트림(읽기 모드)에서의 fflush
   *    - 출력 스트림에 쓰는 `fflush(fp)`와 달리, 키보드 입력(`stdin`) 같은 입력 스트림에 `fflush(stdin)`을
   *      사용하는 것은 C 표준상 정의되지 않은(Undefined Behavior) 잘못된 행동임.
   *    - 입력 버퍼를 비우고 싶을 때는 `fflush`가 아니라 별도의 로직(예: 개행 문자 제거 등)을 사용해야 함.
   * ========================================================================== */

#define _CRT_SECURE_NO_WARNINGS
#include <stdio.h>
#include <stdlib.h>

  // 바이너리 저장 실습을 위한 구조체 정의
typedef struct {
    int id;
    float score;
} Student;

int main(void) {
    // --------------------------------------------------------------------------
    // [실습 1] "w" 모드를 이용한 파일 생성 및 덮어쓰기(Overwriting) 테스트
    // --------------------------------------------------------------------------
    FILE* fp = fopen("practice.txt", "w");
    if (fp == NULL) {
        printf("파일 열기 실패\n");
        return 1;
    }

    fprintf(fp, "첫 번째로 작성된 오리지널 데이터다.\n");
    fclose(fp); // 파일을 닫아야 버퍼의 내용이 디스크에 확실히 기록됨.
    printf("1단계: 파일 생성 및 초기 데이터 작성 완료\n");

    // 동일한 파일명을 "w" 모드로 다시 연다. 
    // 경고: 이 순간 기존에 있던 "첫 번째로 작성된 오리지널 데이터다."는 흔적도 없이 지워진다!
    fp = fopen("practice.txt", "w");
    if (fp == NULL) return 1;

    fprintf(fp, "앗! 'w' 모드로 다시 여는 순간 이전 데이터는 증발하고 덮어씌워졌다.\n");
    fclose(fp);
    printf("2단계: 'w' 모드로 인한 덮어쓰기 완료\n\n");


    // --------------------------------------------------------------------------
    // [실습 2] "a" 모드를 이용한 이어쓰기(Appending) 테스트
    // --------------------------------------------------------------------------
    fp = fopen("practice.txt", "a");
    if (fp == NULL) return 1;

    fprintf(fp, "이 문장은 'a' 모드를 통해 파일의 맨 마지막 줄에 안전하게 이어 붙여진다.\n");
    fprintf(fp, "데이터가 지워지지 않고 살아남았다!\n");

    fclose(fp);
    printf("3단계: 'a' 모드를 통한 이어쓰기 완료\n\n");


    // --------------------------------------------------------------------------
    // [실습 3] "r+" (읽기/쓰기 복합 모드) 실습: 기존 파일 내용 수정하기
    // --------------------------------------------------------------------------
    // "r+" 모드로 기존에 만든 practice.txt를 연다.
    // 기존 파일 내용의 맨 첫 위치(포인터 0)에서 글자를 덮어씌워서 수정할 수 있다.
    fp = fopen("practice.txt", "r+");
    if (fp == NULL) return 1;

    // 맨 앞부분의 내용을 수정(덮어쓰기)함
    fprintf(fp, "[수정됨]");

    // 읽기와 쓰기 작업을 교대할 때는 파일 포인터 위치를 정돈해야 함 (맨 처음으로 이동)
    rewind(fp);

    // 수정된 내용을 바로 읽어서 출력해봄
    char buffer[256];
    printf("4단계: 'r+' 모드로 수정 후 파일 첫 줄 읽기 결과 -> ");
    if (fgets(buffer, sizeof(buffer), fp) != NULL) {
        printf("%s", buffer);
    }
    fclose(fp);
    printf("\n");


    // --------------------------------------------------------------------------
    // [실습 4] 바이너리 모드("wb" / "rb")를 이용한 구조체 통째로 저장 및 읽기
    // --------------------------------------------------------------------------
    Student s1 = { 2026, 98.5f };

    // "wb": 바이너리 쓰기 모드. 문자열 변환 없이 메모리 상의 바이트(비트 패턴) 그대로 디스크에 박제함.
    FILE* bin_fp = fopen("student.dat", "wb");
    if (bin_fp == NULL) return 1;

    // 메모리에 있는 s1 구조체의 크기(sizeof(Student))만큼 바이트를 그대로 스트림으로 쏜다.
    fwrite(&s1, sizeof(Student), 1, bin_fp);
    fclose(bin_fp);
    printf("5단계: 바이너리 모드로 구조체 데이터 통째로 저장 완료\n");

    // "rb": 바이너리 읽기 모드. 변환 과정 없이 디스크의 바이트를 메모리로 그대로 퍼올린다.
    bin_fp = fopen("student.dat", "rb");
    if (bin_fp == NULL) return 1;

    Student s2;
    fread(&s2, sizeof(Student), 1, bin_fp);
    fclose(bin_fp);
    printf("6단계: 바이너리 읽기 결과 -> 학번: %d, 점수: %.1f\n\n", s2.id, s2.score);


    // --------------------------------------------------------------------------
    // [실습 5] 잘못된 모드 조합 에러 시뮬레이션 (읽기 전용 모드에서 쓰기 시도)
    // --------------------------------------------------------------------------
    // 파일을 오직 읽기 전용("r")으로 연다.
    FILE* read_fp = fopen("practice.txt", "r");
    if (read_fp == NULL) return 1;

    printf("7단계: 읽기 전용('r') 모드로 파일을 연 상태에서 쓰기 시도\n");

    // 경고: "r" 모드로 열었기 때문에 아래 fprintf는 정상 작동하지 않거나 쓰기 에러를 발생시킨다!
    int write_result = fprintf(read_fp, "이 문장은 읽기 전용 모드이므로 절대 기록되지 않는다.\n");

    if (write_result < 0) 
    {
        printf("에러 발생: 읽기 전용 스트림에 쓰기를 시도하여 실패함!\n");
    }
    else 
    {
        printf("주의: 시스템에 따라 감지 방식이 달라 반환값이 나올 수 있으나 실제 파일엔 반영되지 않거나 손상됨.\n");
    }

    fclose(read_fp);
    printf("모든 파일 입출력 실습 종료\n");

    return 0;
}