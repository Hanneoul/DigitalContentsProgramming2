/*
================================================================================
 [강의 자료] 전처리기(#define), 조건부 컴파일(#if), 그리고 extern 스토리지가 만났을 때
================================================================================

 1. 오늘 배운 개념들의 총집합
 - extern 스토리지 : 다른 파일(혹은 다른 위치)에 존재하는 전역 변수나 로그 카운터 번호를
   공유해서 사용할 때 핵심적으로 사용됨.
 - static 스토리지 : 로그 번호 카운터처럼 함수가 끝나도 값이 사라지지 않고 계속 증가해야 하는
   데이터를 함수 내부나 파일 내부에서 안전하게 유지할 때 쓰임.
 - 전처리기 조건부 컴파일 (#ifdef / #endif) :
   코드 상단에 특정 매크로(#define _HAN_LOGGER_)가 정의되어 있느냐에 따라
   컴파일러가 코드를 포함할지 아예 무시할지 결정함.

 2. 왜 이런 방식을 쓸까? (디버그 로그의 딜레마)
 - 게임이나 프로그램을 만들 때 개발 중에만 로그를 찍고, 출시(Release) 버전에서는
   로그 출력을 완전히 꺼서 성능을 최적화하고 화면을 깨끗하게 유지하고 싶음.
 - 이때 소스 코드를 일일이 지우는 대신, #define 스위치 하나만 켜고 끄는 방식으로
   로그 시스템 전체를 제어할 수 있음.

 3. ANSI Escape Code를 이용한 컬러 출력
 - 터미널이나 콘솔 창에서 글자 색상을 바꾸기 위해 특수한 제어 문자(\033[36m)를 사용함.
 - 36m은 시안(Cyan, 청록색) 색상을 의미하며, 출력 끝에 \033[0m을 붙여서
   색상이 다음 줄로 번지는 것을 막아줌.
================================================================================
*/

