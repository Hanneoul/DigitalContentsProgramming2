/*
================================================================================
 [강의 자료] 모듈화(Modularization)와 헤더 파일(.h)의 필요성
================================================================================

 1. 왜 코드를 여러 파일로 쪼개야 할까? (모듈화의 개념)
 - 프로그램이 커지면 수만 줄의 코드를 하나의 파일에 다 넣을 수 없음.
 - 담당 기능별로 파일을 쪼개는 것을 '모듈화(Modularization)'라고 부름.
 - 로거는 로거대로, 메인 로직은 메인대로 나누어 관리하면 유지보수가 편해짐.

 2. 헤더 파일(.h)과 소스 파일(.c)의 역할 분담
 - 소스 파일(.c) : 변수가 실제로 태어나는 곳(정의)과 함수가 일하는 곳임.
 - 헤더 파일(.h) : 다른 파일에서 이 기능을 가져다 쓸 수 있도록 돕는 '안내판(선언)'임.
 - 다른 파일들이 이 헤더를 `#include`하면 내부에 무엇이 있는지 알 수 있게 됨.

 3. extern 스키마와 변수 공유
 - 여러 파일이 하나의 전역 변수(예: 로그 카운터)를 동시에 안전하게 공유하려면,
   변수의 진짜 실물은 딱 하나의 .c 파일에만 두고, 헤더에 `extern`으로 선언해 둠.
 - 이렇게 하면 중복 정의 에러 없이 여러 파일에서 변수를 자유롭게 읽고 쓸 수 있음.
================================================================================
*/
#include <stdio.h>
#include "logger.h"

int main(void)
{
    printf("=== 멀티 파일 로거 시스템 시작 ===\n");

    // 로거 함수 호출 테스트
    printDebugLog("네트워크 서버 연결 성공");
    printDebugLog("플레이어 캐릭터 생성 완료");

    // extern으로 공유된 카운터 변수 직접 확인
    printf("현재까지 기록된 총 로그 개수: %d\n", g_logCounter);

    printDebugLog("게임 스테이지 1 진입");

    printf("=== 프로그램 정상 종료 ===\n");

    return 0;
}