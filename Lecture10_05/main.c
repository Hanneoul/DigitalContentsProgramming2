/*
==============================================================================
 [강의 자료] Lecture10_05 | 세이브 슬롯 | 원하는 서랍만 열기
==============================================================================

1. 오늘의 게임 장면
    Forest, Cave, Castle 중 두 번째 세이브만 읽으려 한다.

       slots.dat
       +------------+------------+------------+
       | 1: Forest  | 2: Cave    | 3: Castle  |
       +------------+------------+------------+
       0            S            2*S          3*S
                    ^ S = sizeof(Slot)
    Slot(슬롯)은 끼워 넣는 칸, Offset(오프셋)은 시작점에서 떨어진 거리이다.

 2. 서랍 번호의 비밀
    사용자는 1번부터, 계산은 0번부터이다.
    offset = (number - 1) * sizeof(Slot).
    fseek(fp, offset, SEEK_SET)는 파일 시작에서 offset만큼 이동한다.
    성공은 0이다. 이동 성공 뒤 fread로 한 개를 읽는다.
    ftell은 현재 위치를 반환한다. 여기서는 바이너리 파일의 위치이다.
    sizeof(Slot)을 숫자로 외우면 필드가 바뀔 때 틀어진다.

 3. 작은 실험과 답
    1로 생성 → 2 / 3 / 4로 읽기. 시작 위치가 0, S, 2*S인지 확인한다.
    3번 슬롯은 3*S가 아니라 2*S이다. 앞에 두 칸이 있기 때문이다.
    재실행 후 생성 없이 3을 선택해도 Cave를 읽을 수 있다.
    주의: 메뉴 1은 기존 슬롯 파일을 초기화한다.

 4. 코드 지도
    main → create_slots / read_slot. 추가할 핵심은 offset과 fseek이다.
    선택한 슬롯의 길이와 값을 검사한다. 전체 파일 검증기는 아니다.

 [공통 메모]
 파일은 실행 작업 폴더(VS에서는 프로젝트 폴더)에 생성된다.
 바이너리 구조체 저장은 동일 빌드 환경용이며 필드 변경 시 재생성한다.
 제공된 입력 검사보다 파일 처리 함수부터 읽는다. 실패 안내도 실행 결과이다.

==============================================================================
 [실습 코드] 먼저 실행 → 예측 → 추가 부분 작성 → 다시 실행
==============================================================================
*/

/* 파일 및 표준 입출력 함수를 선언한다. */
#include <stdio.h>
#include "../LectureSupport/console.h" // 공통 화면 도구이다.

/* 표준 종료 코드 EXIT_SUCCESS, EXIT_FAILURE를 사용한다. */
#include <stdlib.h>

/* 문자열 길이 및 문자 검색 함수를 사용한다. */
#include <string.h>

/* -------------------------------------------------------------------------
 * 역할: 키보드 한 줄을 검사하여 메뉴 번호로 바꾼다.
 * 입력: prompt = 안내 문자열, maximum = 허용할 가장 큰 메뉴 번호.
 * 반환: 0~maximum은 선택 번호, -1은 입력 종료 또는 입출력 오류.
 * 예: read_choice("Choose: ", 3)은 0, 1, 2, 3 중 하나를 받는다.
 * 잘못된 입력에는 안내 후 다시 입력받고, 너무 긴 줄의 나머지는 소비한다.
 * ------------------------------------------------------------------------- */
static int read_choice(const char *prompt, int maximum)
{
    /* 한 줄을 받을 배열이다. */
    char line[32];

    /* break 또는 return을 만날 때까지 반복한다. */
    for (;;)
    {
        /* 안내를 표시한다. */
        fputs(prompt, stdout);

        /* 출력 버퍼의 안내 문구를 전달한다. 실패하면 입력 처리를 끝낸다. */
        if (fflush(stdout) == EOF)
        {
            /* 메뉴 입력을 계속할 수 없으므로 종료/오류를 나타내는 -1을 반환한다. */
            return -1;
        }

        /* 한 줄 읽기가 실패했거나 입력이 끝나면 더 이상 배열을 해석하지 않는다. */
        if (fgets(line, sizeof line, stdin) == NULL)
        {
            /* 메뉴 입력을 계속할 수 없으므로 종료/오류를 나타내는 -1을 반환한다. */
            return -1;
        }

        /* 줄바꿈 없이 배열이 채워졌고 EOF도 아니라면 너무 긴 입력으로 처리한다. */
        if (strchr(line, '\n') == NULL && feof(stdin) == 0)
        {
            /* 긴 줄에서 아직 읽지 않은 문자 하나를 받는다. EOF도 담도록 int를 쓴다. */
            int ch = getchar();

            /* 줄바꿈과 EOF가 나올 때까지 긴 입력의 나머지를 소비한다. */
            while (ch != '\n' && ch != EOF)
            {
                /* 다음 문자를 읽는다. 줄바꿈 또는 입력 끝이 나오면 반복을 멈춘다. */
                ch = getchar();
            }

            /* 입력 제한을 안내한다. */
            puts("Input too long. Enter one digit.");

            /* 현재 입력의 처리를 끝내고 반복문의 처음으로 돌아가 다시 입력받는다. */
            continue;
        }

        /* 첫 문자가 허용 범위의 숫자가 아니면 다시 입력받는다. */
        if (line[0] < '0' || line[0] > '0' + maximum)
        {
            /* 잘못된 입력을 안내한다. */
            puts("Enter one valid menu digit.");

            /* 현재 입력의 처리를 끝내고 반복문의 처음으로 돌아가 다시 입력받는다. */
            continue;
        }

        /* 첫 숫자 뒤에서 공백·탭·줄바꿈만 몇 칸 이어지는지 센다. */
        size_t space_count = strspn(line + 1, " \t\r\n");

        /* 숫자 한 칸과 공백 구간을 건너뛴 다음 칸의 번호를 구한다. */
        size_t next_index = 1 + space_count;

        /* 다음 칸이 문자열 끝이 아니면 숫자 뒤에 다른 글자가 섞인 입력이다. */
        if (line[next_index] != '\0')
        {
            /* 잘못된 입력을 안내한다. */
            puts("Enter one valid menu digit.");

            /* 현재 입력의 처리를 끝내고 반복문의 처음으로 돌아가 다시 입력받는다. */
            continue;
        }

        /* 문자 '2'에서 문자 '0'을 빼면 정수 2가 된다. */
        int choice = line[0] - '0';

        /* 검사를 통과한 정수 메뉴 번호를 main에 돌려준다. */
        return choice;
    }
}

/* 슬롯 설명과 작은 게임 상태를 고정 크기로 묶는다. */
typedef struct Slot
{
    /* 슬롯 이름을 보관한다. */
    char name[20];

    /* 캐릭터 레벨이다. */
    int level;

    /* 진행 스테이지이다. */
    int stage;

    /* 소지 골드이다. */
    int gold;
} Slot;

/* -------------------------------------------------------------------------
 * 역할: 서로 다른 예제 슬롯 세 개를 한 파일에 연속 저장한다.
 * 입력: 없음. 프로그램 안의 세 예제 데이터를 사용한다.
 * 반환: 세 개를 모두 쓰고 닫았으면 1, 실패하면 0.
 * 이 메뉴는 기존 slots.dat을 초기화하므로 읽기 메뉴와 구분한다.
 * ------------------------------------------------------------------------- */
static int create_slots(void)
{
    const Slot slots[3] = {

        {"Forest", 2, 1, 100}, {"Cave", 5, 3, 450}, {"Castle", 9, 7, 900}};

    /* 세 슬롯 전체를 새로 기록한다. */
    FILE *fp = fopen("slots.dat", "wb");

    /* 작업의 성공 여부를 저장한다. 이 예제에서는 1이 성공, 0이 실패이다. */
    int ok;

    /* 파일 열기가 실패했다면 포인터를 사용하지 않고 오류를 처리한다. */
    if (fp == NULL)
    {
        /* 실패한 파일 이름과 현재 시스템 오류 설명을 stderr에 표시한다. */
        perror("slots.dat");

        /* 이 사용자 정의 함수의 실패를 호출한 곳에 알리고 실행을 끝낸다. */
        return 0;
    }
    ok = fwrite(slots, sizeof slots[0], 3, fp) == 3;

    /* 앞 단계가 실패했으면 결과를 사용하지 않고 실패를 알린다. */
    if (!ok)
    {
        /* 쓰기 실패를 알린다. */
        fputs("Slot write failed.\n", stderr);
    }

    /* 파일을 닫고 결과를 확인한다. 이 호출 뒤 fp를 다시 사용하지 않는다. */
    if (fclose(fp) == EOF)
    {
        /* 작업 결과나 오류 안내 문구를 지정한 출력 통로로 보낸다. */
        fputs("Slot close failed.\n", stderr);

        /* 작업 실패를 기억하여 나중에 성공했다고 안내하지 않도록 한다. */
        ok = 0;
    }

    /* 읽기/쓰기와 닫기 결과를 모은 성공 여부를 호출한 곳에 돌려준다. */
    return ok;
}

/* -------------------------------------------------------------------------
 * 역할: 파일 안에서 선택한 슬롯 위치로 이동해 그 슬롯 한 개를 읽는다.
 * 입력: number = 사람이 보는 슬롯 번호 1~3.
 * 반환: 위치 이동, 읽기, 닫기, 값 검사가 성공하면 1, 실패하면 0.
 * 슬롯 번호를 먼저 검사하고 (number - 1) * sizeof(Slot)으로 위치를 구한다.
 * ------------------------------------------------------------------------- */
static int read_slot(int number)
{
    /* 열린 파일의 포인터를 보관한다. */
    FILE *fp;

    /* 선택 슬롯을 읽을 객체이다. */
    Slot temporary = {0};

    /* fseek가 요구하는 long 형식의 위치이다. */
    long offset;

    /* 작업의 성공 여부를 저장한다. 이 예제에서는 1이 성공, 0이 실패이다. */
    int ok;
    if (number < 1 || number > 3)
    {
        /* 이 사용자 정의 함수의 실패를 호출한 곳에 알리고 실행을 끝낸다. */
        return 0;
    }
    offset = (long)(number - 1) * (long)sizeof(Slot);

    /* 파일을 읽기 전용으로 연다. */
    fp = fopen("slots.dat", "rb");

    /* 파일 열기가 실패했다면 포인터를 사용하지 않고 오류를 처리한다. */
    if (fp == NULL)
    {
        /* 실패한 파일 이름과 현재 시스템 오류 설명을 stderr에 표시한다. */
        perror("slots.dat (create first)");

        /* 이 사용자 정의 함수의 실패를 호출한 곳에 알리고 실행을 끝낸다. */
        return 0;
    }
    ok = fseek(fp, offset, SEEK_SET) == 0;

    /* 이동 성공 후에만 위치를 확인하고 읽는다. */
    if (ok)
    {
        /* 현재 바이너리 바이트 위치를 받는다. */
        long position = ftell(fp);
        if (position == -1L)
        {
            /* 작업 실패를 기억하여 나중에 성공했다고 안내하지 않도록 한다. */
            ok = 0;
        }
        else
        {
            /* 현재 데이터를 지정한 형식에 맞추어 화면에 표시한다. */
            printf("Slot %d starts at byte %ld.\n", number, position);

            /* 전체 객체를 읽는다. */
            ok = fread(&temporary, sizeof temporary, 1, fp) == 1;
        }
    }

    /* 입출력 오류 표시가 있는지 확인한다. 정상적인 파일 끝과 구분한다. */
    if (ferror(fp))
    {
        /* 작업 실패를 기억하여 나중에 성공했다고 안내하지 않도록 한다. */
        ok = 0;
    }

    /* 파일을 닫고 결과를 확인한다. 이 호출 뒤 fp를 다시 사용하지 않는다. */
    if (fclose(fp) == EOF)
    {
        /* 작업 실패를 기억하여 나중에 성공했다고 안내하지 않도록 한다. */
        ok = 0;
    }

    /* 앞 단계가 실패했으면 결과를 사용하지 않고 실패를 알린다. */
    if (!ok || memchr(temporary.name, '\0', sizeof temporary.name) == NULL ||
        temporary.name[0] == '\0' || temporary.level < 1 || temporary.level > 99 ||
        temporary.stage < 1 || temporary.stage > 10 || temporary.gold < 0 ||

        /* 수치 범위를 검사한다. */
        temporary.gold > 9999)
    {
        /* 작업 결과나 오류 안내 문구를 지정한 출력 통로로 보낸다. */
        fputs("Selected slot is invalid or incomplete.\n", stderr);

        /* 이 사용자 정의 함수의 실패를 호출한 곳에 알리고 실행을 끝낸다. */
        return 0;
    }

    /* 현재 데이터를 지정한 형식에 맞추어 화면에 표시한다. */
    printf("%s level=%d stage=%d gold=%d\n", temporary.name, temporary.level,

           /* 읽은 슬롯을 표시한다. */
           temporary.stage, temporary.gold);

    /* 모든 검사를 통과했으므로 호출한 곳에 성공을 알린다. */
    return 1;
}

/* -------------------------------------------------------------------------
 * 프로그램의 출발점이다. 위쪽에 함수 정의가 있어도 실행은 main에서 시작한다.
 * 필요한 함수를 호출하고, 그 함수가 return하면 호출한 곳의 다음 문장으로 돌아온다.
 * 메뉴형 예제에서는 파일 작업 실패를 안내한 뒤 다시 메뉴를 선택할 수 있다.
 * 마지막 EXIT_SUCCESS / EXIT_FAILURE는 운영체제에 전달할 종료 결과이다.
 * ------------------------------------------------------------------------- */
int main(void)
{
    panel("SAVE ARCHIVE / 10-05"); // 실습 제목이다.
    /* 메뉴 번호이다. */
    int choice;

    /* break 또는 return을 만날 때까지 반복한다. */
    for (;;)
    {
        /* 안내 문구와 최대 메뉴 번호를 넘기고 선택한 정수를 받는다. */
        panel("SAVE SLOTS | [Forest] [Cave] [Castle]"); // 슬롯 카드이다.
        choice = read_choice(
            "1 Create/reset slots / 2 Slot1 / 3 Slot2 / 4 Slot3 / 0 Exit: ", 4);

        /* 0은 종료 메뉴이며 -1은 입력 종료/오류이므로 메뉴 반복을 끝낸다. */
        if (choice <= 0)
        {
            /* 가장 가까운 반복문을 끝내고 반복문 다음으로 이동한다. */
            break;
        }

        /* 메뉴 1번을 선택한 경우의 작업을 실행한다. */
        if (choice == 1)
        {
            /* 사용자 정의 함수를 호출하고 성공을 뜻하는 1일 때만 다음 안내를 실행한다. */
            if (create_slots())
            {
                /* 작업 결과나 오류 안내 문구를 지정한 출력 통로로 보낸다. */
                puts("Three sample slots saved.");
            }
        }
        else
        {
            /* 선택 슬롯 읽기가 실패를 뜻하는 0을 반환하면 오류를 안내한다. */
            if (!read_slot(choice - 1))
            {
                /* 작업 결과나 오류 안내 문구를 지정한 출력 통로로 보낸다. */
                fputs("Slot load failed.\n", stderr);
            }
        }
    }

    /* 입출력 오류 표시가 있는지 확인한다. 정상적인 파일 끝과 구분한다. */
    if (ferror(stdin) != 0 || ferror(stdout) != 0)
    {
        /* 운영체제에 프로그램이 실패로 종료되었음을 알린다. */
        return EXIT_FAILURE;
    }

    /* 운영체제에 프로그램이 정상 종료되었음을 알린다. */
    return EXIT_SUCCESS;
}
